EXACT_CACHE: dict[str, dict[str, Any]] = {}


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def finite_value(m: int) -> sp.Expr:
    return sp.cos(sp.pi / m)


def parse_radical(text: str) -> sp.Expr:
    """Parse a dotted value written with integers, + - * / ( ) and sqrt only."""

    if not re.fullmatch(r"[0-9sqrt()+\-*/. ]+", text):
        raise ValueError(f"unsupported dotted-value expression {text!r}")
    return sp.parse_expr(text, local_dict={"sqrt": sp.sqrt}, evaluate=True)


def root_in_interval(polynomial: str, lower: str, upper: str) -> sp.Expr:
    """The unique real root of a rational polynomial in x inside [lower, upper]."""

    if not re.fullmatch(r"[0-9x^+\-*/() ]+", polynomial):
        raise ValueError(f"unsupported minimal polynomial {polynomial!r}")
    x = sp.Symbol("x")
    poly = sp.Poly(sp.parse_expr(polynomial.replace("^", "**"), local_dict={"x": x}), x)
    low, high = sp.Rational(lower), sp.Rational(upper)
    roots = [root for root in sp.Poly(poly, x).real_roots() if low <= root.evalf(60) <= high]
    if len(roots) != 1:
        raise ValueError(f"{polynomial} has {len(roots)} real roots in [{lower}, {upper}]")
    return roots[0]


def dotted_value(entry: dict[str, Any]) -> sp.Expr:
    """Dotted values come either as radicals or as minimal polynomial plus isolating interval."""

    if "expression" in entry:
        return parse_radical(entry["expression"])
    interval = entry["isolating_interval"]
    return root_in_interval(entry["minimal_polynomial"], interval["lower"], interval["upper"])


def exact_real(expr: sp.Expr) -> dict[str, Any]:
    key = sp.srepr(expr)
    if key not in EXACT_CACHE:
        x = sp.Symbol("x")
        poly = sp.Poly(sp.minpoly(expr, x), x)
        decimal = float(sp.N(expr, 30))
        width = max(1e-10, abs(decimal) * 1e-12)
        EXACT_CACHE[key] = {
            "kind": "algebraic-real",
            "decimal": decimal,
            "minimalPolynomial": [int(c) for c in poly.all_coeffs()],
            "isolatingInterval": [decimal - width, decimal + width],
        }
    return dict(EXACT_CACHE[key])


def inertia(matrix: list[list[sp.Expr]]) -> dict[str, Any]:
    mpmath.mp.dps = 80
    numeric = mpmath.matrix([[sp.N(entry, 90) for entry in row] for row in matrix])
    eigenvalues = sorted(float(value) for value in mpmath.eigsy(numeric)[0])
    zero = [value for value in eigenvalues if abs(value) < 1e-40]
    smallest_nonzero = min(abs(value) for value in eigenvalues if abs(value) >= 1e-40)
    return {
        "positive": sum(1 for value in eigenvalues if value >= 1e-40),
        "negative": sum(1 for value in eigenvalues if value <= -1e-40),
        "zero": len(zero),
        "rank": len(eigenvalues) - len(zero),
        "rankMethod": "80-digit symmetric eigenvalues; zero means |lambda| < 1e-40",
        "largestZeroEigenvalue": max((abs(value) for value in zero), default=0.0),
        "smallestNonzeroEigenvalue": smallest_nonzero,
    }


def build_polytope(
    *,
    name: str,
    description: str,
    matrix: list[list[int | str]],
    dotted: dict[tuple[int, int], sp.Expr],
    source_refs: list[dict[str, Any]],
    ref_id: str,
    command: str,
    diagnostics: dict[str, Any],
    notes: list[str],
) -> dict[str, Any]:
    n = len(matrix)
    gram: list[list[sp.Expr]] = [[sp.Integer(1 if i == j else 0) for j in range(n)] for i in range(n)]
    normal_gram: list[list[dict[str, Any]]] = []
    dotted_rows = []
    for i in range(n):
        row = []
        for j in range(n):
            m = matrix[i][j]
            if i == j:
                row.append({"kind": "numericGram", "value": 1, "sourceRefId": ref_id})
            elif m == "inf":
                value = dotted[(min(i, j), max(i, j))]
                gram[i][j] = -value
                exact = exact_real(value)
                row.append({"kind": "dotted", "coshDistance": exact["decimal"], "sourceRefId": ref_id, "exact": exact})
                if i < j:
                    dotted_rows.append({"edge": [i, j], **{k: exact[k] for k in ("decimal", "minimalPolynomial", "isolatingInterval")}})
            elif m == 2:
                row.append({"kind": "right", "sourceRefId": ref_id})
            else:
                gram[i][j] = -finite_value(int(m))
                row.append({"kind": "coxeter", "m": int(m), "sourceRefId": ref_id})
        normal_gram.append(row)
    signature = inertia(gram)
    expected = {"positive": 5, "negative": 1, "zero": n - 6, "rank": 6}
    if {k: signature[k] for k in expected} != expected:
        raise ValueError(f"{name}: Gram inertia {signature} is not {expected}")
    return {
        "schemaVersion": 1,
        "name": name,
        "description": description,
        "rank": n,
        "generators": [{"id": f"f{i}", "label": f"F{i + 1}"} for i in range(n)],
        "coxeterMatrix": matrix,
        "geometry": {"model": "hyperboloid", "dimension": 5, "projection": "klein-pca", "normalGram": normal_gram},
        "dataStatus": "certified",
        "sourceRefs": source_refs,
        "certificate": {
            "status": "passed",
            "backend": BACKEND,
            "backendVersion": BACKEND_VERSION,
            "scopes": ["source-transcription", "gram-signature"],
            "command": command,
            "sourceRefIds": [ref["id"] for ref in source_refs],
            "diagnostics": {
                **diagnostics,
                "signature": signature,
                "dottedWeights": dotted_rows,
                "nonClaims": [
                    "not a CoxIter or Vinberg-algorithm compactness check run in this repository",
                    "not a quotient, manifold, or PL Morse certificate",
                    "geometric coordinates are still produced numerically by the viewer",
                ],
            },
        },
        "notes": notes,
        "warnings": [
            "Geometric rendering factors normalGram numerically for visualization.",
            "The 3D projection is a drawing convention and does not certify hyperbolic distances or intersections.",
        ],
    }


def coxiter_checker_summary(stem: str, source_ref_ids: list[str]) -> dict[str, Any] | None:
    """Summary of a stored CoxIter artifact (scripts/coxiter_check_compact.py --write-artifact)."""

    artifact_path = Path("scripts/certificates/coxiter") / f"{stem}.coxiter.json"
    if not artifact_path.exists():
        return None
    artifact = json.loads(artifact_path.read_text(encoding="utf-8"))
    coxiter = artifact.get("coxiter", {})
    return {
        "status": coxiter.get("status", "skipped"),
        "backend": "coxiterCompactDiagramChecker",
        "backendVersion": "1.0.0",
        "checker": "CoxIter",
        "scopes": ["coxiter-diagram"],
        "command": f"python scripts/coxiter_check_compact.py public/examples/{stem}.json --require-external",
        "inputHash": artifact.get("inputHash"),
        "outputHash": sha256_file(artifact_path),
        "sourceRefIds": source_ref_ids,
        "diagnostics": {
            "artifactPath": artifact_path.as_posix(),
            "coxiterGraphSha256": artifact.get("coxiterGraphSha256"),
            "parsed": coxiter.get("parsed", {}),
            "nonClaims": [
                "CoxIter checks the prepared diagram input (cocompactness, f-vector, Euler characteristic); its numerical signature is not used.",
                "The in-repo catalogue certifier owns source transcription and normal-Gram diagnostics.",
            ],
        },
        "warnings": [] if coxiter.get("status") == "passed" else ["CoxIter artifact is not a passed external diagram check."],
    }


def with_checker(stem: str, example: dict[str, Any]) -> dict[str, Any]:
    summary = coxiter_checker_summary(stem, [ref["id"] for ref in example["sourceRefs"]])
    if summary is not None:
        example["checkerSummaries"] = [summary]
    return example


def mazheng_stem(label: str) -> str:
    found = re.fullmatch(r"P_\{(\d+)(?:,(\d+))?\}", label)
    if not found:
        raise ValueError(f"unexpected Ma--Zheng label {label}")
    kind, index = found.groups()
    return f"mazheng_5d_9facet_p{kind}" + (f"_{int(index):02d}" if index else "")


def mazheng_examples() -> dict[str, dict[str, Any]]:
    if sha256_file(MAZHENG_SOURCE) != MAZHENG_SOURCE_SHA256:
        raise ValueError(f"{MAZHENG_SOURCE} does not match its pinned SHA-256")
    examples: dict[str, dict[str, Any]] = {}
    for line in MAZHENG_SOURCE.read_text(encoding="utf-8").splitlines():
        record = json.loads(line)
        if record.get("status") != "verified" or record.get("facets") != 9 or record.get("dimension") != 5:
            raise ValueError(f"unexpected record {record.get('canonical_key')}")
        certificates = {cert["type"]: cert for cert in record["certificates"]}
        label = certificates["source"]["published_label"]
        n = len(record["nodes"])
        matrix: list[list[int | str]] = [[1 if i == j else 2 for j in range(n)] for i in range(n)]
        for edge in record["ordinary_edges"]:
            matrix[edge["i"]][edge["j"]] = matrix[edge["j"]][edge["i"]] = int(edge["m"])
        values = certificates["dotted_values"]["values"]
        dotted: dict[tuple[int, int], sp.Expr] = {}
        for edge in record["dotted_edges"]:
            i, j = sorted((edge["i"], edge["j"]))
            matrix[i][j] = matrix[j][i] = "inf"
            entry = values[edge["var"]]
            if [i, j] not in [sorted(pair) for pair in entry["pairs"]]:
                raise ValueError(f"{label}: dotted variable {edge['var']} does not name pair {(i, j)}")
            dotted[(i, j)] = dotted_value(entry)
        sage = certificates.get("sage_validator", {})
        stem = mazheng_stem(label)
        examples[stem] = build_polytope(
            name=f"Ma-Zheng 5D nine-facet {label.replace('_{', '').replace('}', '')}",
            description="Compact hyperbolic Coxeter 5-polytope with 9 facets from the Ma--Zheng classification.",
            matrix=matrix,
            dotted=dotted,
            source_refs=[{**MAZHENG_REF, "locator": f"Classification table entry {label}; dotted lengths from the length table."}, CENSUS_REF],
            ref_id=MAZHENG_REF["id"],
            command=f"python scripts/certify_compact_5d_catalogue.py public/examples/{stem}.json",
            diagnostics={
                "publishedLabel": label,
                "combinatorialType": record["combinatorial_type_id"],
                "sourceTranscription": MAZHENG_SOURCE.as_posix(),
                "sourceSha256": MAZHENG_SOURCE_SHA256,
                "sourceCanonicalKey": record["canonical_key"],
                "sourceSageInertia": sage.get("computed_inertia"),
                "claims": [
                    "facet-labelled Coxeter matrix and dotted values match the pinned 10Facets5D verified record",
                    "normal Gram rank 6 and inertia (5,1,3)",
                ],
            },
            notes=[
                f"Ma--Zheng label {label}, combinatorial type {record['combinatorial_type_id']}. Facet labels F1..F9 follow the 10Facets5D facet labelling of that type.",
                "The source catalogue records an exact Sage algebraic-number inertia check; this repository recomputes the inertia from 80-digit eigenvalues.",
                "Normal coordinates and chamber basepoints are computed numerically from normalGram; geometric mode is visualization-grade.",
            ],
        )
    if len(examples) != 51:
        raise ValueError(f"expected 51 nine-facet polytopes, got {len(examples)}")
    return examples


def h5_example() -> dict[str, Any]:
    if sha256_file(H5_SOURCE) != H5_SOURCE_SHA256:
        raise ValueError(f"{H5_SOURCE} does not match its pinned SHA-256")
    source = json.loads(H5_SOURCE.read_text(encoding="utf-8"))
    matrix = source["coxeterMatrix"]
    pair = source["ultraparallelPair"]
    value = parse_radical(pair["cosh_distance"])
    figure_value = sp.sqrt(3 + sp.sqrt(2)) / 2
    if sp.simplify(value - figure_value) != 0:
        raise ValueError("H5-P7-22 dotted value does not match the Ma--Zheng prism figure")
    return build_polytope(
        name="H5-P7-22 compact simplicial 5-prism",
        description="Compact hyperbolic Coxeter simplicial 5-prism with 7 facets (Kaplinskaja; Ma--Zheng prism figure, bottom diagram). Its certified Sylow-7 torsion-free cover of index 39,628,800 lives in h5-p7-22_index39628800/.",
        matrix=matrix,
        dotted={(min(pair["i"], pair["j"]), max(pair["i"], pair["j"])): value},
        source_refs=[MAZHENG_PRISM_REF, KAPLINSKAJA_REF],
        ref_id=MAZHENG_PRISM_REF["id"],
        command=f"python scripts/certify_compact_5d_catalogue.py public/examples/{H5_STEM}.json",
        diagnostics={
            "sourceTranscription": H5_SOURCE.as_posix(),
            "sourceSha256": H5_SOURCE_SHA256,
            "claims": [
                "Coxeter matrix matches h5-p7-22_index39628800/coxeter_system.json",
                "dotted value sqrt((3+sqrt(2))/4) equals the figure label (1/2) sqrt(3+sqrt(2))",
                "normal Gram rank 6 and inertia (5,1,1)",
            ],
        },
        notes=[
            "This is the third compact simplicial 5-prism, besides Makarov P0 [5,3,3,3,3] and P2 [5,3,3,3,4].",
            "The large cover is not bundled: see h5-p7-22_index39628800/README.md and docs/low-barycentric-morse.md for the cover, its walls, and the low-barycentric results.",
            "Normal coordinates and chamber basepoints are computed numerically from normalGram; geometric mode is visualization-grade.",
        ],
    )


def all_examples() -> dict[str, dict[str, Any]]:
    built = {H5_STEM: h5_example(), **mazheng_examples()}
    return {stem: with_checker(stem, example) for stem, example in built.items()}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("examples", nargs="*", type=Path)
    parser.add_argument("--write-examples", action="store_true")
    args = parser.parse_args()
    built = all_examples()
    if args.write_examples:
        for stem, example in built.items():
            for directory in EXAMPLE_DIRS:
                (directory / f"{stem}.json").write_text(json.dumps(example, indent=2) + "\n", encoding="utf-8", newline="\n")
        print(json.dumps({"written": len(built)}))
        return 0
    paths = args.examples or sorted(
        [Path("public/examples") / f"{H5_STEM}.json", *Path("public/examples").glob("mazheng_5d_9facet_*.json")]
    )
    results = []
    for path in paths:
        stem = path.stem
        errors = []
        if stem not in built:
            errors.append("unknown example")
        elif json.loads(path.read_text(encoding="utf-8")) != json.loads(json.dumps(built[stem])):
            errors.append("stored example differs from a fresh build")
        results.append({"path": path.as_posix(), "ok": not errors, "errors": errors})
    ok = all(result["ok"] for result in results) and len(results) > 0
    print(json.dumps({"ok": ok, "backend": BACKEND, "backendVersion": BACKEND_VERSION, "results": results}, indent=2))
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
