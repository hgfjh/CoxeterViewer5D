#!/usr/bin/env python3
"""Certify and write the H5-P7-22 prism and the Ma--Zheng nine-facet catalogue.

Two sources of compact hyperbolic Coxeter 5-polytopes are turned into viewer
examples here:

* ``H5-P7-22`` (7 facets): the third compact simplicial 5-prism of Kaplinskaja's
  classification, as drawn in Ma--Zheng's Figure "Compact simplicial prisms in
  H^5".  The transcription is ``h5-p7-22_index39628800/coxeter_system.json``.
* The 51 compact 5-polytopes with 9 facets of Ma--Zheng (arXiv:2203.16049).
  ``scripts/data/mazheng_9facet_verified.jsonl`` is a pinned copy of the
  verified catalogue of the 10Facets5D census workspace
  (``data/baselines/d5_m9/verified.jsonl`` at commit 65380c1), which carries
  facet-labelled Coxeter labels, exact dotted values from the Ma--Zheng length
  table, and an exact Sage algebraic-number inertia check.

For each polytope this script builds the normal Gram matrix with exact
algebraic dotted weights (stored as minimal polynomial plus isolating interval),
and recomputes the rank and inertia from 80-digit eigenvalues.  A compact
hyperbolic 5-polytope with ``n`` facets has a Gram matrix of rank 6 and
inertia ``(5, 1, n - 6)``.  That is the same standard as
``certify_tumarkin_8facet.py``.  The examples are written with
``--write-examples``; without it, the listed (or all) examples are validated
against a fresh build.
"""

