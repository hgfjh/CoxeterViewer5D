class DisjointSet {
  private readonly parent = new Map<string, string>();

  add(value: string) {
    if (!this.parent.has(value)) this.parent.set(value, value);
  }

  find(value: string): string {
    const parent = this.parent.get(value);
    if (parent === undefined) {
      throw new Error(`Unknown disjoint-set element ${value}.`);
    }
    if (parent === value) return value;
    const root = this.find(parent);
    this.parent.set(value, root);
    return root;
  }

  union(left: string, right: string) {
    const leftRoot = this.find(left);
    const rightRoot = this.find(right);
    if (leftRoot === rightRoot) return;
    if (leftRoot.localeCompare(rightRoot) < 0) {
      this.parent.set(rightRoot, leftRoot);
    } else {
      this.parent.set(leftRoot, rightRoot);
    }
  }

  components(): string[][] {
    const result = new Map<string, string[]>();
    for (const value of this.parent.keys()) {
      const root = this.find(value);
      const component = result.get(root) ?? [];
      component.push(value);
      result.set(root, component);
    }
    return [...result.values()]
      .map((component) => component.sort())
      .sort((left, right) => left[0].localeCompare(right[0]));
  }
}

/**
 * Construct deck orbits of quotient walls from complete opposite-edge data.
 * The union-find computes only wall incidence. Two-sidedness is a separate
 * exact statement about kernel loops and must replay in `sideTransport`.
 */
export function buildExactSymbolicWallOrbitCatalogue(
  cover: SymbolicRegularKernelCover,
  incidence: ExactSymbolicWallIncidenceCatalogue,
): ExactSymbolicWallOrbitCatalogue {
  const errors: string[] = [];
  if (incidence.sourceCoverId !== cover.id) {
    errors.push("The wall-incidence catalogue belongs to another cover.");
  }
  validatePassedChecks(incidence.checks, "Wall-incidence catalogue", errors);
  if (!isScientificSha256(incidence.certificateHash)) {
    errors.push(
      "The wall-incidence catalogue lacks a SHA-256 certificate hash.",
    );
  }
  validateOrbitPartitionReplay(
    incidence.orbitPartitionReplay,
    incidence.wallOrbitEvidence
      .map((wall) => wall.representativeWallKey)
      .sort(),
    "Wall orbit",
    errors,
  );
  validateOrbitActionObjects(
    incidence.orbitPartitionReplay,
    incidence.wallOrbitEvidence.map((wall) => wall.representativeWallKey),
    "Wall orbit",
    errors,
  );

  const rankOneCells = cover.sphericalCellOrbits.filter(
    (cell) => cell.dimension === 1,
  );
  const rankTwoCells = cover.sphericalCellOrbits.filter(
    (cell) => cell.dimension === 2,
  );
  const rankOneById = new Map(rankOneCells.map((cell) => [cell.id, cell]));
  const rankTwoById = new Map(rankTwoCells.map((cell) => [cell.id, cell]));
  const edgeById = new Map<string, SymbolicEdgeDeckOrbitDescriptor>();
  const edgeCellIds = new Set<string>();
  const walls = new DisjointSet();

  for (const edge of incidence.edgeOrbits) {
    if (edgeById.has(edge.id)) {
      errors.push(`Edge deck orbit ${edge.id} is repeated.`);
      continue;
    }
    edgeById.set(edge.id, edge);
    walls.add(edge.id);
    const cell = rankOneById.get(edge.sphericalCellOrbitId);
    if (cell === undefined) {
      errors.push(
        `${edge.id} does not reference a rank-one spherical cell orbit.`,
      );
      continue;
    }
    if (edgeCellIds.has(cell.id)) {
      errors.push(`Rank-one cell orbit ${cell.id} has multiple edge records.`);
    }
    edgeCellIds.add(cell.id);
    if (cell.generators.length !== 1 || cell.generators[0] !== edge.generator) {
      errors.push(`${edge.id} has the wrong Coxeter generator.`);
    }
    try {
      if (
        positiveExactInteger(edge.edgeCount, `${edge.id} edge count`) !==
        exactIntegerToBigInt(cell.cellCount)
      ) {
        errors.push(`${edge.id} has a stale edge-orbit cardinality.`);
      }
    } catch (error) {
      if (error instanceof SymbolicRegularCoverError)
        errors.push(...error.errors);
      else throw error;
    }
  }
  for (const cell of rankOneCells) {
    if (!edgeCellIds.has(cell.id)) {
      errors.push(`Rank-one cell orbit ${cell.id} is missing.`);
    }
  }

  const representedRankTwoCounts = new Map<string, bigint>();
  const seenRankTwoRepresentatives = new Set<string>();
  for (const cellOrbit of incidence.rankTwoCellOrbits) {
    if (seenRankTwoRepresentatives.has(cellOrbit.id)) {
      errors.push(`Rank-two incidence representative ${cellOrbit.id} repeats.`);
      continue;
    }
    seenRankTwoRepresentatives.add(cellOrbit.id);
    if (!isScientificSha256(cellOrbit.certificateHash)) {
      errors.push(`${cellOrbit.id} lacks a SHA-256 boundary certificate.`);
    }
    const sphericalCell = rankTwoById.get(cellOrbit.sphericalCellOrbitId);
    if (sphericalCell === undefined) {
      errors.push(
        `${cellOrbit.id} does not reference a rank-two spherical cell orbit.`,
      );
      continue;
    }
    const sphericalOrder = exactIntegerToBigInt(
      sphericalCell.sphericalSubgroupOrder,
    );
    const expectedM = sphericalOrder / 2n;
    if (
      sphericalOrder % 2n !== 0n ||
      !Number.isSafeInteger(cellOrbit.m) ||
      BigInt(cellOrbit.m) !== expectedM
    ) {
      errors.push(`${cellOrbit.id} has an incorrect relation order m.`);
    }
    if (cellOrbit.boundaryEdgeOrbitIds.length !== 2 * cellOrbit.m) {
      errors.push(
        `${cellOrbit.id} must contain the complete ${2 * cellOrbit.m}-edge boundary.`,
      );
      continue;
    }
    for (const edgeOrbitId of cellOrbit.boundaryEdgeOrbitIds) {
      if (!edgeById.has(edgeOrbitId)) {
        errors.push(
          `${cellOrbit.id} references unknown edge orbit ${edgeOrbitId}.`,
        );
      }
    }
    if (
      cellOrbit.boundaryEdgeOrbitIds.every((edgeOrbitId) =>
        edgeById.has(edgeOrbitId),
      )
    ) {
      for (let index = 0; index < cellOrbit.m; index += 1) {
        walls.union(
          cellOrbit.boundaryEdgeOrbitIds[index],
          cellOrbit.boundaryEdgeOrbitIds[index + cellOrbit.m],
        );
      }
    }
    try {
      const represented = positiveExactInteger(
        cellOrbit.representedCellCount,
        `${cellOrbit.id} represented cell count`,
      );
      representedRankTwoCounts.set(
        sphericalCell.id,
        (representedRankTwoCounts.get(sphericalCell.id) ?? 0n) + represented,
      );
    } catch (error) {
      if (error instanceof SymbolicRegularCoverError)
        errors.push(...error.errors);
      else throw error;
    }
  }
  for (const cell of rankTwoCells) {
    const represented = representedRankTwoCounts.get(cell.id) ?? 0n;
    const expected = exactIntegerToBigInt(cell.cellCount);
    if (represented !== expected) {
      errors.push(
        `Rank-two cell orbit ${cell.id} represents ${represented} cells; expected ${expected}.`,
      );
    }
  }

  const computedComponents = walls.components();
  const evidenceByComponent = new Map<string, SymbolicWallOrbitEvidence>();
  const deckOrder = exactIntegerToBigInt(cover.deckGroup.order);
  for (const evidence of incidence.wallOrbitEvidence) {
    const componentKey = [...new Set(evidence.edgeOrbitIds)].sort().join("|");
    if (evidenceByComponent.has(componentKey)) {
      errors.push(`Wall component ${componentKey} has repeated evidence.`);
      continue;
    }
    evidenceByComponent.set(componentKey, evidence);
    validatePassedChecks(
      evidence.sideTransport.checks,
      `${evidence.id} side transport`,
      errors,
    );
    if (!isScientificSha256(evidence.sideTransport.certificateHash)) {
      errors.push(`${evidence.id} lacks a SHA-256 side-transport certificate.`);
    }
    if (
      !evidence.sideTransport.complete ||
      !evidence.sideTransport.twoSided ||
      !evidence.sideTransport.stabilizerPreservesSides
    ) {
      errors.push(
        `${evidence.id} does not have complete, two-sided side transport.`,
      );
    }
    try {
      const wallCount = positiveExactInteger(
        evidence.wallCount,
        `${evidence.id} wall count`,
      );
      const stabilizerOrder = positiveExactInteger(
        evidence.stabilizerOrder,
        `${evidence.id} stabilizer order`,
      );
      if (wallCount * stabilizerOrder !== deckOrder) {
        errors.push(`${evidence.id} fails exact orbit-stabilizer.`);
      }
    } catch (error) {
      if (error instanceof SymbolicRegularCoverError)
        errors.push(...error.errors);
      else throw error;
    }
  }
  for (const component of computedComponents) {
    const key = component.join("|");
    if (!evidenceByComponent.has(key)) {
      errors.push(`Computed wall component ${key} has no exact evidence.`);
    }
  }
  for (const key of evidenceByComponent.keys()) {
    if (!computedComponents.some((component) => component.join("|") === key)) {
      errors.push(
        `Declared wall component ${key} is not generated by opposite edges.`,
      );
    }
  }
  if (errors.length > 0) {
    throw new SymbolicRegularCoverError(
      "Cannot construct exact symbolic wall orbits",
      errors,
    );
  }

  const wallOrbits = computedComponents.map((component) => {
    const evidence = evidenceByComponent.get(component.join("|"));
    if (evidence === undefined)
      throw new Error("Validated wall evidence vanished.");
    return {
      id: evidence.id,
      representativeWallKey: evidence.representativeWallKey,
      representativeGenerator: evidence.representativeGenerator,
      wallCount: evidence.wallCount,
      stabilizerOrder: evidence.stabilizerOrder,
      twoSided: true,
      sideStabilizerPreserving: true,
      certificateHash: evidence.sideTransport.certificateHash,
    } satisfies SymbolicWallDeckOrbitDescriptor;
  });
  wallOrbits.sort((left, right) => left.id.localeCompare(right.id));
  return attachVerifierBrand(
    {
      status: "passed",
      method: "exact-rank-two-opposite-edge-orbits",
      sourceCoverId: cover.id,
      exhaustive: incidence.exhaustive,
      wallOrbits,
      checks: {
        deckOrbitPartitionVerified: true,
        stabilizerOrdersVerified: true,
        twoSidednessVerified: true,
        rankTwoOppositeIncidenceVerified: true,
        sideTransportVerified: true,
      },
      sourceIncidenceHash: incidence.certificateHash,
      orbitPartitionReplayHash: incidence.orbitPartitionReplay.replayHash,
      certificateHash: scientificSha256({
        coverId: cover.id,
        incidenceHash: incidence.certificateHash,
        wallOrbits,
      }),
    },
    VERIFIED_WALL_CATALOGUE,
  );
}

function validatePassedChecks(
  checks: Record<string, boolean>,
  label: string,
  errors: string[],
) {
  const failed = Object.entries(checks)
    .filter(([, passed]) => !passed)
    .map(([check]) => check);
  if (failed.length > 0) {
    errors.push(`${label} checks did not pass: ${failed.join(", ")}.`);
  }
}

function validateOrbitPartitionReplay(
  replay: ExactOrbitPartitionReplay,
  expectedCanonicalKeys: readonly string[],
  label: string,
  errors: string[],
) {
  if (!hasVerifierBrand(replay, VERIFIED_ORBIT_PARTITION)) {
    errors.push(
      `${label} partition is assertion-only; replay it from a complete action table before certification.`,
    );
  }
  validatePassedChecks(replay.checks, `${label} partition replay`, errors);
  if (!isScientificSha256(replay.replayHash)) {
    errors.push(`${label} partition replay lacks a SHA-256 replay hash.`);
  }
  const declared = [...replay.canonicalRepresentativeKeys];
  const canonical = [...new Set(declared)].sort();
  const expected = [...new Set(expectedCanonicalKeys)].sort();
  if (
    declared.length !== canonical.length ||
    declared.some((value, index) => value !== canonical[index])
  ) {
    errors.push(`${label} canonical representatives are repeated or unsorted.`);
  }
  if (
    canonical.length !== expected.length ||
    canonical.some((value, index) => value !== expected[index])
  ) {
    errors.push(
      `${label} partition replay is bound to different representatives.`,
    );
  }
  const replayFacts = verifiedOrbitPartitionFacts.get(replay);
  if (
    hasVerifierBrand(replay, VERIFIED_ORBIT_PARTITION) &&
    (replayFacts === undefined || !replayFacts.sideTransportConsistent)
  ) {
    errors.push(`${label} has no verified transport/stabilizer replay facts.`);
  }
}

function validateOrbitActionObjects(
  replay: ExactOrbitPartitionReplay,
  expectedObjectKeys: readonly string[],
  label: string,
  errors: string[],
) {
  const facts = verifiedOrbitPartitionFacts.get(replay);
  const expected = [...new Set(expectedObjectKeys)].sort();
  if (
    facts === undefined ||
    facts.objectKeys.length !== expected.length ||
    facts.objectKeys.some((key, index) => key !== expected[index])
  ) {
    errors.push(`${label} action table is bound to a different object set.`);
  }
}

/**
 * Build sign variables for symmetry orbits of exact quotient walls.
 * A variable sign is transported to its entire wall orbit by the supplied
 * signed-action certificate; it is not an independent sign for every wall.
 */
export function buildSymmetryRestrictedWallSpace(
  cover: SymbolicRegularKernelCover,
  input: BuildSymmetryRestrictedWallSpaceInput,
): SymmetryRestrictedWallSpace {
  const { symmetry, wallCatalogue, variables, partitionCertificate } = input;
  const errors: string[] = [];
  const deckOrder = exactIntegerToBigInt(cover.deckGroup.order);
  let symmetryOrder = 0n;
  try {
    symmetryOrder = positiveExactInteger(symmetry.order, "symmetry order");
  } catch (error) {
    if (error instanceof SymbolicRegularCoverError)
      errors.push(...error.errors);
    else throw error;
  }
  if (symmetry.deckGroupId !== cover.deckGroup.id) {
    errors.push("The symmetry subgroup belongs to another deck group.");
  }
  if (symmetry.action !== "left-deck-transformations") {
    errors.push("The symmetry subgroup must act by left deck transformations.");
  }
  if (symmetryOrder > 0n && deckOrder % symmetryOrder !== 0n) {
    errors.push(
      `Symmetry order ${symmetryOrder} does not divide deck-group order ${deckOrder}.`,
    );
  }
  validatePassedChecks(
    symmetry.certificate.checks,
    "Symmetry subgroup certificate",
    errors,
  );
  if (wallCatalogue.sourceCoverId !== cover.id) {
    errors.push("The wall catalogue belongs to another symbolic cover.");
  }
  validatePassedChecks(
    wallCatalogue.checks,
    "Wall catalogue certificate",
    errors,
  );
  if (
    partitionCertificate.sourceCoverId !== cover.id ||
    partitionCertificate.symmetrySubgroupId !== symmetry.id
  ) {
    errors.push("The wall partition certificate has stale source metadata.");
  }
  validatePassedChecks(
    partitionCertificate.checks,
    "Symmetry wall partition certificate",
    errors,
  );

  const wallOrbitById = new Map<string, SymbolicWallDeckOrbitDescriptor>();
  for (const orbit of wallCatalogue.wallOrbits) {
    if (wallOrbitById.has(orbit.id)) {
      errors.push(`Wall deck orbit ${orbit.id} is repeated.`);
      continue;
    }
    wallOrbitById.set(orbit.id, orbit);
    if (
      !Number.isInteger(orbit.representativeGenerator) ||
      orbit.representativeGenerator < 0 ||
      orbit.representativeGenerator >= cover.systemRank
    ) {
      errors.push(`${orbit.id} has an invalid representative generator.`);
    }
    let wallCount = 0n;
    let stabilizerOrder = 0n;
    try {
      wallCount = positiveExactInteger(
        orbit.wallCount,
        `${orbit.id} wall count`,
      );
      stabilizerOrder = positiveExactInteger(
        orbit.stabilizerOrder,
        `${orbit.id} stabilizer order`,
      );
    } catch (error) {
      if (error instanceof SymbolicRegularCoverError) {
        errors.push(...error.errors);
      } else throw error;
    }
    if (wallCount * stabilizerOrder !== deckOrder) {
      errors.push(
        `${orbit.id} violates orbit-stabilizer: ${wallCount} * ${stabilizerOrder} != ${deckOrder}.`,
      );
    }
    if (!orbit.twoSided || !orbit.sideStabilizerPreserving) {
      errors.push(
        `${orbit.id} does not admit a globally transported two-sided coorientation.`,
      );
    }
  }

  const seenVariables = new Set<string>();
  const variableCounts = new Map<string, bigint>();
  const builtVariables: SymmetryRestrictedWallVariable[] = [];
  for (const variable of variables) {
    if (seenVariables.has(variable.id)) {
      errors.push(`Wall variable ${variable.id} is repeated.`);
      continue;
    }
    seenVariables.add(variable.id);
    const orbit = wallOrbitById.get(variable.wallDeckOrbitId);
    if (orbit === undefined) {
      errors.push(
        `Wall variable ${variable.id} references unknown orbit ${variable.wallDeckOrbitId}.`,
      );
      continue;
    }
    let wallCount = 0n;
    try {
      wallCount = positiveExactInteger(
        variable.wallCount,
        `${variable.id} wall count`,
      );
    } catch (error) {
      if (error instanceof SymbolicRegularCoverError) {
        errors.push(...error.errors);
      } else throw error;
    }
    variableCounts.set(
      orbit.id,
      (variableCounts.get(orbit.id) ?? 0n) + wallCount,
    );
    if (!variable.stabilizerPreservesSides) {
      errors.push(
        `${variable.id} has a side-reversing stabilizer, so a sign cannot be assigned to its symmetry orbit.`,
      );
    }
    if (variable.sideTransportCertificateHash.trim().length === 0) {
      errors.push(
        `${variable.id} is missing its side-transport certificate hash.`,
      );
    }
    builtVariables.push({
      id: variable.id,
      wallDeckOrbitId: variable.wallDeckOrbitId,
      representativeWallKey: variable.representativeWallKey,
      wallCount: toExactIntegerValue(wallCount),
      allowedSigns: [-1, 1] as const,
      signTransport: "certified-symmetry-action",
      sideTransportCertificateHash: variable.sideTransportCertificateHash,
    });
  }

  for (const orbit of wallCatalogue.wallOrbits) {
    const expected = exactIntegerToBigInt(orbit.wallCount);
    const actual = variableCounts.get(orbit.id) ?? 0n;
    if (actual !== expected) {
      errors.push(
        `Symmetry variables cover ${actual} walls in ${orbit.id}; expected ${expected}.`,
      );
    }
  }
  if (errors.length > 0) {
    throw new SymbolicRegularCoverError(
      "Cannot build the symmetry-restricted wall space",
      errors,
    );
  }

  builtVariables.sort((left, right) => left.id.localeCompare(right.id));
  const restrictedSearchComplete = wallCatalogue.exhaustive;
  const coverCompleteness = cover.completeness;
  const completeness: SymbolicRegularCoverCompletenessScope = {
    ...coverCompleteness,
    exactClaims: restrictedSearchComplete
      ? [...coverCompleteness.exactClaims, "symmetry-restricted-wall-search"]
      : coverCompleteness.exactClaims,
    wallSearch: {
      kind: "symmetry-restricted",
      symmetrySubgroupId: symmetry.id,
      exhaustiveWithinRestrictedSpace: restrictedSearchComplete,
      exhaustiveWithoutSymmetryRestriction: false,
    },
    promotionGate: { ...coverCompleteness.promotionGate },
    prohibitedClaims: [...coverCompleteness.prohibitedClaims],
  };
  return attachVerifierBrand(
    {
      schemaVersion: 1,
      kind: "symmetry-restricted-wall-space",
      sourceCoverId: cover.id,
      symmetry,
      wallCatalogueHash: wallCatalogue.certificateHash,
      partitionCertificateHash: partitionCertificate.certificateHash,
      variables: builtVariables,
      exactWithinRestrictedSpace: restrictedSearchComplete,
      completeness,
      warnings: [
        ...(wallCatalogue.exhaustive
          ? []
          : [
              "The supplied deck-wall catalogue is not exhaustive; the variables are complete only for its recorded wall orbits.",
            ]),
        "Symmetry-related walls share transported signs. This is not an unrestricted wall-coorientation search.",
      ],
    },
    VERIFIED_WALL_SPACE,
  );
}

/** Assign signs to all symmetry variables, defaulting unspecified signs to +1. */
export function createSymmetryRestrictedCoorientation(
  wallSpace: SymmetryRestrictedWallSpace,
  requestedSigns: Partial<Record<string, SymbolicOrientationSign>> = {},
): SymmetryRestrictedWallCoorientation {
  const errors: string[] = [];
  const variablesById = new Map(
    wallSpace.variables.map((variable) => [variable.id, variable]),
  );
  for (const variableId of Object.keys(requestedSigns).sort()) {
    if (!variablesById.has(variableId)) {
      errors.push(`Unknown symmetry wall variable ${variableId}.`);
    }
  }
  const variableSigns: Record<string, SymbolicOrientationSign> = {};
  const representativeWallSigns: SymmetryRestrictedWallCoorientation["representativeWallSigns"] =
    [];
  for (const variable of wallSpace.variables) {
    const requested = requestedSigns[variable.id];
    const sign = requested ?? 1;
    if (sign !== 1 && sign !== -1) {
      errors.push(
        `Wall variable ${variable.id} has invalid sign ${String(sign)}.`,
      );
      variableSigns[variable.id] = 1;
    } else {
      variableSigns[variable.id] = sign;
    }
    representativeWallSigns.push({
      variableId: variable.id,
      representativeWallKey: variable.representativeWallKey,
      sign: variableSigns[variable.id],
    });
  }
  return {
    kind: "symmetry-restricted-wall-coorientation",
    sourceCoverId: wallSpace.sourceCoverId,
    symmetrySubgroupId: wallSpace.symmetry.id,
    variableSigns,
    representativeWallSigns,
    exactWithinRestrictedSpace:
      errors.length === 0 && wallSpace.exactWithinRestrictedSpace,
    valid: errors.length === 0,
    errors,
    completeness: wallSpace.completeness,
  };
}

function validateCellBoundaryCatalogue(
  cover: SymbolicRegularKernelCover,
  wallSpace: SymmetryRestrictedWallSpace,
  catalogue: ExactSymbolicCellBoundaryCatalogue,
): void {
  const errors: string[] = [];
  if (catalogue.sourceCoverId !== cover.id) {
    errors.push("The cell-boundary catalogue belongs to another cover.");
  }
  if (catalogue.wallSpaceHash !== symbolicWallSpaceDigest(wallSpace)) {
    errors.push("The cell-boundary catalogue is bound to another wall space.");
  }
  validatePassedChecks(catalogue.checks, "Cell-boundary catalogue", errors);
  if (!isScientificSha256(catalogue.certificateHash)) {
    errors.push(
      "The cell-boundary catalogue lacks a SHA-256 certificate hash.",
    );
  }
  validateOrbitPartitionReplay(
    catalogue.orbitPartitionReplay,
    catalogue.representatives.map((representative) => representative.id).sort(),
    "Cell orbit",
    errors,
  );
  validateOrbitActionObjects(
    catalogue.orbitPartitionReplay,
    catalogue.representatives.map((representative) => representative.id),
    "Cell orbit",
    errors,
  );
  const variables = new Set(wallSpace.variables.map((variable) => variable.id));
  const rankTwoCells = new Map(
    cover.sphericalCellOrbits
      .filter((cell) => cell.dimension === 2)
      .map((cell) => [cell.id, cell]),
  );
  const representedCounts = new Map<string, bigint>();
  const seen = new Set<string>();
  for (const representative of catalogue.representatives) {
    if (seen.has(representative.id)) {
      errors.push(`Cell-boundary representative ${representative.id} repeats.`);
      continue;
    }
    seen.add(representative.id);
    if (!isScientificSha256(representative.certificateHash)) {
      errors.push(`${representative.id} lacks a SHA-256 boundary replay hash.`);
    }
    const cell = rankTwoCells.get(representative.sphericalCellOrbitId);
    if (cell === undefined) {
      errors.push(
        `${representative.id} does not reference a rank-two spherical cell orbit.`,
      );
      continue;
    }
    const m = exactIntegerToBigInt(cell.sphericalSubgroupOrder) / 2n;
    if (BigInt(representative.boundary.length) !== 2n * m) {
      errors.push(
        `${representative.id} does not contain its complete ${2n * m}-step boundary.`,
      );
    }
    for (const step of representative.boundary) {
      if (!variables.has(step.variableId)) {
        errors.push(
          `${representative.id} references unknown wall variable ${step.variableId}.`,
        );
      }
      if (step.orientation !== 1 && step.orientation !== -1) {
        errors.push(`${representative.id} has a non-oriented boundary step.`);
      }
    }
    try {
      const represented = positiveExactInteger(
        representative.representedCellCount,
        `${representative.id} represented cell count`,
      );
      representedCounts.set(
        cell.id,
        (representedCounts.get(cell.id) ?? 0n) + represented,
      );
    } catch (error) {
      if (error instanceof SymbolicRegularCoverError)
        errors.push(...error.errors);
      else throw error;
    }
  }
  if (catalogue.exhaustive) {
    for (const cell of rankTwoCells.values()) {
      const represented = representedCounts.get(cell.id) ?? 0n;
      const expected = exactIntegerToBigInt(cell.cellCount);
      if (represented !== expected) {
        errors.push(
          `Cell-boundary representatives cover ${represented} cells in ${cell.id}; expected ${expected}.`,
        );
      }
    }
  }
  if (errors.length > 0) {
    throw new SymbolicRegularCoverError(
      "Cannot replay symbolic cellular boundaries",
      errors,
    );
  }
  if (!hasVerifierBrand(catalogue, VERIFIED_BOUNDARY_CATALOGUE)) {
    attachVerifierBrand(catalogue, VERIFIED_BOUNDARY_CATALOGUE);
  }
}

/** Check the cellular 1-cocycle on every supplied rank-two cell orbit. */
export function checkExactSymbolicCellularCocycle(
  cover: SymbolicRegularKernelCover,
  wallSpace: SymmetryRestrictedWallSpace,
  coorientation: SymmetryRestrictedWallCoorientation,
  catalogue: ExactSymbolicCellBoundaryCatalogue,
): ExactSymbolicCellularCocycleCertificate {
  validateCellBoundaryCatalogue(cover, wallSpace, catalogue);
  const failures: string[] = [];
  if (
    !coorientation.valid ||
    coorientation.sourceCoverId !== cover.id ||
    coorientation.symmetrySubgroupId !== wallSpace.symmetry.id
  ) {
    failures.push(
      "The coorientation is invalid or belongs to another wall space.",
    );
  }
  const checks = catalogue.representatives.map((representative) => {
    const signedBoundaryValues = representative.boundary.map((step) => {
      const sign = coorientation.variableSigns[step.variableId];
      if (sign === undefined) {
        failures.push(
          `${representative.id} has no sign for ${step.variableId}.`,
        );
        return 0;
      }
      return step.orientation * sign;
    });
    const sum = signedBoundaryValues.reduce((total, value) => total + value, 0);
    const passed = sum === 0;
    if (!passed) {
      failures.push(
        `${representative.id} has signed boundary sum ${sum}, not zero.`,
      );
    }
    return {
      representativeId: representative.id,
      sphericalCellOrbitId: representative.sphericalCellOrbitId,
      representedCellCount: representative.representedCellCount,
      signedBoundaryValues,
      sum,
      passed,
    };
  });
  const coorientationHash = symbolicCoorientationDigest(coorientation);
  const status =
    failures.length > 0
      ? "failed"
      : catalogue.exhaustive
        ? "passed"
        : "incomplete";
  return attachVerifierBrand(
    {
      status,
      sourceCoverId: cover.id,
      wallSpaceHash: symbolicWallSpaceDigest(wallSpace),
      coorientationHash,
      boundaryCatalogueHash: catalogue.certificateHash,
      exhaustive: catalogue.exhaustive,
      checks,
      failures,
      replayHash: scientificSha256({
        coverId: cover.id,
        coorientationHash,
        boundaryCatalogueHash: catalogue.certificateHash,
        checks,
      }),
    },
    VERIFIED_COCYCLE,
  );
}

/**
 * Exhaust the finite symmetry-restricted sign cube up to the supplied cap.
 * A found solution is globally valid after exact transport. A failed restricted
 * search is never evidence that an unrestricted coorientation does not exist.
 */
export function searchSymmetryRestrictedCoorientations(
  cover: SymbolicRegularKernelCover,
  wallSpace: SymmetryRestrictedWallSpace,
  catalogue: ExactSymbolicCellBoundaryCatalogue,
  options: SearchSymmetryRestrictedCoorientationsOptions = {},
): SymmetryRestrictedCoorientationSearchResult {
  validateCellBoundaryCatalogue(cover, wallSpace, catalogue);
  const maxAssignments = options.maxAssignments ?? 1_048_576;
  if (!Number.isSafeInteger(maxAssignments) || maxAssignments < 1) {
    throw new SymbolicRegularCoverError("Invalid coorientation search cap", [
      "maxAssignments must be a positive safe integer.",
    ]);
  }
  const variableIds = wallSpace.variables.map((variable) => variable.id);
  const totalAssignments = 1n << BigInt(variableIds.length);
  const assignmentsToVisit =
    totalAssignments > BigInt(maxAssignments)
      ? maxAssignments
      : Number(totalAssignments);
  let assignmentsVisited = 0;
  let candidateTestsReplayed = 0;
  let candidateReplayComplete = true;
  for (let mask = 0; mask < assignmentsToVisit; mask += 1) {
    const exactMask = BigInt(mask);
    const signs: Record<string, SymbolicOrientationSign> = {};
    for (let index = 0; index < variableIds.length; index += 1) {
      signs[variableIds[index]] =
        (exactMask & (1n << BigInt(index))) === 0n ? 1 : -1;
    }
    const coorientation = createSymmetryRestrictedCoorientation(
      wallSpace,
      signs,
    );
    const cocycle = checkExactSymbolicCellularCocycle(
      cover,
      wallSpace,
      coorientation,
      catalogue,
    );
    assignmentsVisited += 1;
    if (cocycle.status === "passed") {
      const candidateTest = options.testCandidate?.(coorientation, cocycle);
      if (candidateTest !== undefined) {
        candidateTestsReplayed += 1;
        if (!isScientificSha256(candidateTest.replayHash)) {
          candidateReplayComplete = false;
          continue;
        }
        if (!candidateTest.accepted) continue;
      }
      return attachVerifierBrand(
        {
          status: "solution-found",
          sourceCoverId: cover.id,
          wallSpaceHash: symbolicWallSpaceDigest(wallSpace),
          boundaryCatalogueHash: catalogue.certificateHash,
          assignmentsVisited,
          candidateTestsReplayed,
          totalAssignments: toExactIntegerValue(totalAssignments),
          exhaustiveWithinRestrictedSpace:
            BigInt(assignmentsVisited) === totalAssignments,
          unrestrictedConclusion: "existence-certified",
          solution: coorientation,
          cocycle,
          warnings: [
            "The solution uses symmetry-transported signs. Its existence is exact; the search did not enumerate arbitrary independent wall signs.",
          ],
        },
        VERIFIED_COORIENTATION_SEARCH,
      );
    }
  }
  const exhaustive =
    BigInt(assignmentsVisited) === totalAssignments &&
    wallSpace.exactWithinRestrictedSpace &&
    catalogue.exhaustive &&
    candidateReplayComplete;
  return attachVerifierBrand(
    {
      status: exhaustive
        ? "no-solution-in-restricted-space"
        : "search-incomplete",
      sourceCoverId: cover.id,
      wallSpaceHash: symbolicWallSpaceDigest(wallSpace),
      boundaryCatalogueHash: catalogue.certificateHash,
      assignmentsVisited,
      candidateTestsReplayed,
      totalAssignments: toExactIntegerValue(totalAssignments),
      exhaustiveWithinRestrictedSpace: exhaustive,
      unrestrictedConclusion: "inconclusive",
      warnings: [
        exhaustive
          ? "No symmetry-restricted sign assignment passed. This does not rule out a nonsymmetric coorientation."
          : "The restricted sign search or one of its catalogues was incomplete; no negative conclusion is allowed.",
      ],
    },
    VERIFIED_COORIENTATION_SEARCH,
  );
}

/** Flip one restricted sign variable without changing the symmetry partition. */
export function flipSymmetryRestrictedWallVariable(
  wallSpace: SymmetryRestrictedWallSpace,
  coorientation: SymmetryRestrictedWallCoorientation,
  variableId: string,
): SymmetryRestrictedWallCoorientation {
  if (!wallSpace.variables.some((variable) => variable.id === variableId)) {
    return {
      ...coorientation,
      variableSigns: { ...coorientation.variableSigns },
      representativeWallSigns: [...coorientation.representativeWallSigns],
      exactWithinRestrictedSpace: false,
      valid: false,
      errors: [
        ...coorientation.errors,
        `Unknown symmetry wall variable ${variableId}.`,
      ],
    };
  }
  return createSymmetryRestrictedCoorientation(wallSpace, {
    ...coorientation.variableSigns,
    [variableId]: coorientation.variableSigns[variableId] === -1 ? 1 : -1,
  });
}

/**
 * Replay a complete Reidemeister-Schreier generating set against the wall
 * cocycle. Dividing by the image gcd changes only the scale of the character,
 * not its directed links, and supplies the primitive map when the image is
 * nonzero.
 */
export function certifyExactSymbolicSchreierHomomorphism(
  cover: SymbolicRegularKernelCover,
  coorientation: SymmetryRestrictedWallCoorientation,
  oracle: ExactSymbolicSchreierOracle,
): ExactSymbolicSchreierHomomorphismCertificate {
  const failures: string[] = [];
  const coorientationHash = symbolicCoorientationDigest(coorientation);
  if (oracle.sourceCoverId !== cover.id) {
    failures.push("The Schreier oracle belongs to another symbolic cover.");
  }
  if (oracle.coorientationHash !== coorientationHash) {
    failures.push("The Schreier oracle is bound to another coorientation.");
  }
  validatePassedChecks(oracle.checks, "Schreier oracle", failures);
  validateOrbitPartitionReplay(
    oracle.transversalOrbitPartitionReplay,
    [...oracle.transversalRepresentativeKeys].sort(),
    "Schreier transversal",
    failures,
  );
  validateOrbitActionObjects(
    oracle.transversalOrbitPartitionReplay,
    oracle.transversalRepresentativeKeys,
    "Schreier transversal",
    failures,
  );
  if (!coorientation.valid) failures.push("The coorientation is invalid.");
  if (!isScientificSha256(oracle.certificateHash)) {
    failures.push("The Schreier oracle lacks a SHA-256 certificate hash.");
  }

  const seenGenerators = new Set<string>();
  const replayedValues: Array<{
    seed: SymbolicSchreierGeneratorSeed;
    value: bigint;
    replayHash: string;
  }> = [];
  let everyLoopCloses = true;
  for (const seed of oracle.generators) {
    if (seenGenerators.has(seed.id)) {
      failures.push(`Schreier generator ${seed.id} repeats.`);
      continue;
    }
    seenGenerators.add(seed.id);
    if (
      !Number.isInteger(seed.generator) ||
      seed.generator < 0 ||
      seed.generator >= cover.systemRank
    ) {
      failures.push(`Schreier generator ${seed.id} uses an invalid generator.`);
      continue;
    }
    const replay = oracle.replayGenerator(seed, coorientation);
    if (!replay.closesInKernel) {
      everyLoopCloses = false;
      failures.push(`${seed.id} does not replay as a loop in the kernel.`);
    }
    if (!isScientificSha256(replay.replayHash)) {
      failures.push(`${seed.id} has no SHA-256 replay hash.`);
    }
    replayedValues.push({
      seed,
      value: replay.value,
      replayHash: replay.replayHash,
    });
  }

  let imageGcd = 0n;
  for (const record of replayedValues) {
    imageGcd = greatestCommonDivisor(imageGcd, record.value);
  }
  const nonzeroImage = imageGcd > 0n;
  if (!nonzeroImage) {
    failures.push("Every Schreier generator has value zero.");
  }
  const bezout = bezoutCoefficients(
    replayedValues.map((record) => record.value),
  );
  const bezoutCombination = replayedValues.reduce(
    (sum, record, index) => sum + record.value * bezout.coefficients[index],
    0n,
  );
  const bezoutIdentityVerified =
    bezout.gcd === imageGcd && bezoutCombination === imageGcd;
  if (!bezoutIdentityVerified) {
    failures.push(
      "The exported Bezout coefficients do not certify the image gcd.",
    );
  }
  const generatorValues: SymbolicSchreierGeneratorValue[] = replayedValues.map(
    ({ seed, value, replayHash }) => ({
      id: seed.id,
      sourceDeckElementKey: seed.sourceDeckElementKey,
      generator: seed.generator,
      targetTransversalDeckElementKey: seed.targetTransversalDeckElementKey,
      kernelWord: [...seed.kernelWord],
      value: toSignedIntegerValue(value),
      normalizedValue: toSignedIntegerValue(
        imageGcd === 0n ? 0n : value / imageGcd,
      ),
      replayHash,
    }),
  );
  const normalizedById = new Map(
    generatorValues.map((record) => [
      record.id,
      signedIntegerToBigInt(
        record.normalizedValue,
        `${record.id} normalized value`,
      ),
    ]),
  );

  let everyRelationReplayed = true;
  const relationChecks = oracle.relations.map((relation) => {
    let normalizedSum = 0n;
    for (const term of relation.terms) {
      const value = normalizedById.get(term.generatorId);
      if (value === undefined) {
        failures.push(
          `${relation.id} references unknown Schreier generator ${term.generatorId}.`,
        );
        continue;
      }
      if (!Number.isSafeInteger(term.exponent)) {
        failures.push(`${relation.id} has a nonintegral exponent.`);
        continue;
      }
      normalizedSum += value * BigInt(term.exponent);
    }
    const replay = oracle.replayRelation(relation);
    if (!replay.closesInKernel || !isScientificSha256(replay.replayHash)) {
      everyRelationReplayed = false;
      failures.push(
        `${relation.id} did not replay as an exact kernel relation.`,
      );
    }
    if (normalizedSum !== 0n) {
      failures.push(
        `${relation.id} has normalized character sum ${normalizedSum}, not zero.`,
      );
    }
    return {
      relationId: relation.id,
      normalizedSum: toSignedIntegerValue(normalizedSum),
      closesInKernel: replay.closesInKernel,
      replayHash: replay.replayHash,
      passed:
        replay.closesInKernel &&
        isScientificSha256(replay.replayHash) &&
        normalizedSum === 0n,
    };
  });
  const everyRelationValueZero = relationChecks.every((check) => check.passed);
  const status =
    failures.length > 0
      ? "failed"
      : oracle.exhaustive
        ? "passed"
        : "incomplete";
  const replayHash = scientificSha256({
    coverId: cover.id,
    coorientationHash,
    oracleCertificateHash: oracle.certificateHash,
    generatorValues,
    relationChecks,
    imageGcd: imageGcd.toString(),
    bezoutCoefficients: bezout.coefficients.map((value) => value.toString()),
  });
  return attachVerifierBrand(
    {
      status,
      sourceCoverId: cover.id,
      coorientationHash,
      oracleCertificateHash: oracle.certificateHash,
      exhaustive: oracle.exhaustive,
      generatorValues,
      relationChecks,
      imageGcd: toExactIntegerValue(imageGcd),
      normalizationDivisor: toExactIntegerValue(imageGcd),
      bezoutCoefficients: replayedValues.map((record, index) => ({
        generatorId: record.seed.id,
        coefficient: toSignedIntegerValue(bezout.coefficients[index]),
      })),
      bezoutCombination: toSignedIntegerValue(bezoutCombination),
      rawMapPrimitive: imageGcd === 1n,
      normalizedMapPrimitive: imageGcd > 0n,
      checks: {
        everySchreierGeneratorReplayed:
          replayedValues.length === oracle.generators.length,
        everySchreierLoopCloses: everyLoopCloses,
        everyPresentationRelationReplayed: everyRelationReplayed,
        everyRelationValueZero,
        nonzeroImage,
        bezoutIdentityVerified,
      },
      failures,
      replayHash,
    },
    VERIFIED_SCHREIER,
  );
}

/**
 * Verify the symbolic pulling subdivision and perturbed PL height model.
 *
 * Legacy replay records are retained as diagnostics, but cannot mint the
 * runtime verifier brand used by fibering promotion. Exact promotion requires
 * an executable oracle returning raw vertices, simplices, and edge periods;
 * every check and archival hash below is then recomputed in this module.
 */
export function certifyExactSymbolicPullingMorseModel(
  cover: SymbolicRegularKernelCover,
  coorientation: SymmetryRestrictedWallCoorientation,
  schreier: ExactSymbolicSchreierHomomorphismCertificate,
  source: ExactSymbolicPullingMorseReplay | ExactSymbolicPullingMorseOracle,
): ExactSymbolicPullingMorseCertificate {
  const failures: string[] = [];
  const coorientationHash = symbolicCoorientationDigest(coorientation);
  const emptyChecks: ExactSymbolicPullingMorseReplay["checks"] = {
    globalVertexOrderTotal: false,
    simplexOrbitCatalogueComplete: false,
    pullingTriangulationsCompatibleOnFaces: false,
    wallCocycleIntegratedToVertexHeights: false,
    rationalOffsetsBreakEveryTie: false,
    rationalOffsetsPreserveEveryDirectedEdge: false,
    quotientPeriodicOffsets: false,
    affineExtensionOnEverySimplex: false,
    deckEquivarianceReplayed: false,
  };
  if (!("recompute" in source)) {
    failures.push(
      "Assertion-only pulling-Morse records are diagnostic; exact certification requires executable recomputation from raw subdivision and height data.",
    );
    return deepFreeze({
      status: "incomplete",
      sourceCoverId: cover.id,
      coorientationHash,
      schreierCertificateHash: schreier.replayHash,
      exhaustive: false,
      globalVertexOrderSha256: source.globalVertexOrderSha256,
      simplexOrbitCatalogueSha256: source.simplexOrbitCatalogueSha256,
      integratedHeightSha256: source.integratedHeightSha256,
      rationalOffsetSha256: source.rationalOffsetSha256,
      offsetDenominator: source.offsetDenominator,
      simplexOrbitPartitionReplayHash:
        source.simplexOrbitPartitionReplay.replayHash,
      checks: emptyChecks,
      failures,
      replayHash: scientificSha256({ diagnosticOnly: source }),
    });
  }
  if (!hasVerifierBrand(schreier, VERIFIED_SCHREIER)) {
    failures.push("The pulling-Morse oracle requires a replayed Schreier map.");
  }

  let raw: ExactSymbolicPullingMorseRawData;
  try {
    raw = source.recompute({ cover, coorientation, schreier });
  } catch (error) {
    failures.push(
      `The pulling-Morse oracle did not complete: ${error instanceof Error ? error.message : String(error)}.`,
    );
    raw = {
      exhaustive: false,
      vertices: [],
      simplices: [],
      directedEdges: [],
      simplexOrbitAction: {
        method: `${source.method}:failed`,
        objectKeys: [],
        generatorIds: [],
        transitions: [],
      },
    };
  }

  const vertexIds = raw.vertices.map((vertex) => vertex.id);
  const globalVertexOrder = [...new Set(vertexIds)].sort();
  const globalVertexOrderTotal =
    globalVertexOrder.length === vertexIds.length && vertexIds.length > 0;
  if (!globalVertexOrderTotal) {
    failures.push("Raw pulling data has no vertices or repeats a vertex id.");
  }
  let representedVertexCount = 0n;
  const integratedHeight = new Map<string, bigint>();
  for (const vertex of raw.vertices) {
    try {
      representedVertexCount += vertex.representedVertexCount
        ? positiveExactInteger(
            vertex.representedVertexCount,
            `${vertex.id} represented vertex count`,
          )
        : 1n;
      integratedHeight.set(
        vertex.id,
        signedIntegerToBigInt(
          vertex.integratedHeight,
          `${vertex.id} integrated height`,
        ),
      );
    } catch (error) {
      if (error instanceof SymbolicRegularCoverError)
        failures.push(...error.errors);
      else throw error;
    }
  }
  if (
    raw.exhaustive &&
    representedVertexCount !==
      exactIntegerToBigInt(cover.vertexOrbit.vertexCount)
  ) {
    failures.push(
      `Pulling vertex representatives cover ${representedVertexCount} vertices; expected ${cover.vertexOrbit.vertexCount.decimal}.`,
    );
  }

  const vertexSet = new Set(globalVertexOrder);
  const simplexIds = raw.simplices.map((simplex) => simplex.id);
  const seenSimplexIds = new Set<string>();
  const canonicalSimplices: SymbolicPullingSimplexSeed[] = [];
  let pullingTriangulationsCompatibleOnFaces = true;
  let affineExtensionOnEverySimplex = true;
  for (const simplex of raw.simplices) {
    const vertices = [...new Set(simplex.vertexIds)].sort();
    if (
      seenSimplexIds.has(simplex.id) ||
      vertices.length === 0 ||
      vertices.length !== simplex.vertexIds.length ||
      vertices.some((vertex) => !vertexSet.has(vertex))
    ) {
      pullingTriangulationsCompatibleOnFaces = false;
      affineExtensionOnEverySimplex = false;
      failures.push(
        `${simplex.id} is not a valid simplex on the global vertex order.`,
      );
      continue;
    }
    seenSimplexIds.add(simplex.id);
    canonicalSimplices.push({ id: simplex.id, vertexIds: vertices });
  }
  canonicalSimplices.sort((left, right) => left.id.localeCompare(right.id));
  if (canonicalSimplices.length === 0) {
    failures.push(
      "The pulling-Morse oracle returned no simplex representatives.",
    );
    affineExtensionOnEverySimplex = false;
  }

  let simplexOrbitPartition: ExactOrbitPartitionReplay | undefined;
  try {
    simplexOrbitPartition = replayExactOrbitPartition(raw.simplexOrbitAction);
    validateOrbitPartitionReplay(
      simplexOrbitPartition,
      simplexOrbitPartition.canonicalRepresentativeKeys,
      "Simplex orbit",
      failures,
    );
    validateOrbitActionObjects(
      simplexOrbitPartition,
      simplexIds,
      "Simplex orbit",
      failures,
    );
  } catch (error) {
    if (error instanceof SymbolicRegularCoverError)
      failures.push(...error.errors);
    else throw error;
  }
  const simplexOrbitCatalogueComplete =
    raw.exhaustive &&
    simplexOrbitPartition !== undefined &&
    canonicalSimplices.length === simplexIds.length;

  const orderIndex = new Map(
    globalVertexOrder.map((vertex, index) => [vertex, BigInt(index)]),
  );
  const offsetDenominatorBigInt = BigInt(globalVertexOrder.length + 1);
  const variableIds = new Set(Object.keys(coorientation.variableSigns));
  const usedVariableIds = new Set<string>();
  let wallCocycleIntegratedToVertexHeights = raw.directedEdges.length > 0;
  let rationalOffsetsPreserveEveryDirectedEdge = raw.directedEdges.length > 0;
  const edgeIds = new Set<string>();
  for (const edge of raw.directedEdges) {
    if (edgeIds.has(edge.id)) {
      failures.push(`Pulling edge ${edge.id} repeats.`);
      wallCocycleIntegratedToVertexHeights = false;
      rationalOffsetsPreserveEveryDirectedEdge = false;
      continue;
    }
    edgeIds.add(edge.id);
    const sourceHeight = integratedHeight.get(edge.sourceVertexId);
    const targetHeight = integratedHeight.get(edge.targetVertexId);
    const sourceOffset = orderIndex.get(edge.sourceVertexId);
    const targetOffset = orderIndex.get(edge.targetVertexId);
    const variableSign = coorientation.variableSigns[edge.variableId];
    if (
      sourceHeight === undefined ||
      targetHeight === undefined ||
      sourceOffset === undefined ||
      targetOffset === undefined ||
      variableSign === undefined
    ) {
      failures.push(
        `${edge.id} references an unknown vertex or wall variable.`,
      );
      wallCocycleIntegratedToVertexHeights = false;
      rationalOffsetsPreserveEveryDirectedEdge = false;
      continue;
    }
    usedVariableIds.add(edge.variableId);
    let periodShift = 0n;
    try {
      periodShift = edge.periodShift
        ? signedIntegerToBigInt(edge.periodShift, `${edge.id} period shift`)
        : 0n;
    } catch (error) {
      if (error instanceof SymbolicRegularCoverError)
        failures.push(...error.errors);
      else throw error;
    }
    const expected = BigInt(variableSign * edge.orientation);
    const liftedDifference = targetHeight + periodShift - sourceHeight;
    if (liftedDifference !== expected) {
      wallCocycleIntegratedToVertexHeights = false;
      failures.push(
        `${edge.id} has lifted height difference ${liftedDifference}; expected ${expected}.`,
      );
    }
    const perturbedDifference =
      liftedDifference * offsetDenominatorBigInt + targetOffset - sourceOffset;
    if (
      perturbedDifference === 0n ||
      perturbedDifference > 0n !== expected > 0n
    ) {
      rationalOffsetsPreserveEveryDirectedEdge = false;
      failures.push(
        `${edge.id} reverses or flattens after the rational offset.`,
      );
    }
  }
  if ([...variableIds].some((variableId) => !usedVariableIds.has(variableId))) {
    wallCocycleIntegratedToVertexHeights = false;
    failures.push(
      "The pulling edge catalogue does not replay every wall variable.",
    );
  }
  let rationalOffsetsBreakEveryTie = true;
  for (const simplex of canonicalSimplices) {
    const values = simplex.vertexIds.map(
      (vertex) =>
        (integratedHeight.get(vertex) ?? 0n) * offsetDenominatorBigInt +
        (orderIndex.get(vertex) ?? 0n),
    );
    if (new Set(values.map(String)).size !== values.length) {
      rationalOffsetsBreakEveryTie = false;
      failures.push(
        `${simplex.id} retains an equal-height pair after perturbation.`,
      );
    }
  }
  const checks: ExactSymbolicPullingMorseReplay["checks"] = {
    globalVertexOrderTotal,
    simplexOrbitCatalogueComplete,
    pullingTriangulationsCompatibleOnFaces,
    wallCocycleIntegratedToVertexHeights,
    rationalOffsetsBreakEveryTie,
    rationalOffsetsPreserveEveryDirectedEdge,
    quotientPeriodicOffsets: globalVertexOrderTotal,
    affineExtensionOnEverySimplex,
    deckEquivarianceReplayed:
      simplexOrbitPartition !== undefined && raw.exhaustive,
  };
  validatePassedChecks(checks, "Pulling-Morse recomputation", failures);
  const globalVertexOrderSha256 = scientificSha256(globalVertexOrder);
  const simplexOrbitCatalogueSha256 = scientificSha256(canonicalSimplices);
  const integratedHeightSha256 = scientificSha256(
    [...integratedHeight.entries()]
      .map(([vertex, height]) => [vertex, height.toString()])
      .sort(([left], [right]) => left.localeCompare(right)),
  );
  const rationalOffsetSha256 = scientificSha256(
    [...orderIndex.entries()]
      .map(([vertex, offset]) => [vertex, offset.toString()])
      .sort(([left], [right]) => left.localeCompare(right)),
  );
  const status =
    failures.length > 0 ? "failed" : raw.exhaustive ? "passed" : "incomplete";
  const result: ExactSymbolicPullingMorseCertificate = {
    status,
    sourceCoverId: cover.id,
    coorientationHash,
    schreierCertificateHash: schreier.replayHash,
    exhaustive: raw.exhaustive,
    globalVertexOrderSha256,
    simplexOrbitCatalogueSha256,
    integratedHeightSha256,
    rationalOffsetSha256,
    offsetDenominator: toExactIntegerValue(offsetDenominatorBigInt),
    simplexOrbitPartitionReplayHash:
      simplexOrbitPartition?.replayHash ??
      scientificSha256("missing-partition"),
    checks,
    failures,
    replayHash: scientificSha256({
      coverId: cover.id,
      coorientationHash,
      schreierHash: schreier.replayHash,
      method: source.method,
      raw,
      globalVertexOrderSha256,
      simplexOrbitCatalogueSha256,
      integratedHeightSha256,
      rationalOffsetSha256,
      checks,
    }),
  };
  return status === "passed"
    ? attachVerifierBrand(result, VERIFIED_PULLING_MORSE)
    : deepFreeze(result);
}

function canonicalizeComplex(
  complex: SymbolicFiniteSimplicialComplex,
  label: string,
  errors: string[],
): SymbolicFiniteSimplicialComplex {
  const vertices = [...new Set(complex.vertices)].sort();
  if (vertices.length !== complex.vertices.length) {
    errors.push(`${label} repeats a link vertex.`);
  }
  const vertexSet = new Set(vertices);
  const facetKeys = new Set<string>();
  const facets: string[][] = [];
  for (const rawFacet of complex.facets) {
    const facet = [...new Set(rawFacet)].sort();
    if (facet.length !== rawFacet.length || facet.length === 0) {
      errors.push(`${label} contains an empty or repeated-vertex facet.`);
      continue;
    }
    if (facet.some((vertex) => !vertexSet.has(vertex))) {
      errors.push(`${label} has a facet containing an unknown vertex.`);
      continue;
    }
    const key = facet.join("\u0000");
    if (!facetKeys.has(key)) {
      facetKeys.add(key);
      facets.push(facet);
    }
  }
  facets.sort((left, right) =>
    left.join("\u0000").localeCompare(right.join("\u0000")),
  );
  return { vertices, facets };
}

function inducedComplex(
  full: SymbolicFiniteSimplicialComplex,
  includedVertices: Set<string>,
): SymbolicFiniteSimplicialComplex {
  const vertices = full.vertices.filter((vertex) =>
    includedVertices.has(vertex),
  );
  const candidates = full.facets
    .map((facet) => facet.filter((vertex) => includedVertices.has(vertex)))
    .filter((facet) => facet.length > 0);
  for (const vertex of vertices) {
    if (!candidates.some((facet) => facet.includes(vertex)))
      candidates.push([vertex]);
  }
  const unique = new Map(
    candidates.map((facet) => [facet.join("\u0000"), facet]),
  );
  const facets = [...unique.values()].filter(
    (candidate) =>
      ![...unique.values()].some(
        (other) =>
          other.length > candidate.length &&
          candidate.every((vertex) => other.includes(vertex)),
      ),
  );
  facets.sort((left, right) =>
    left.join("\u0000").localeCompare(right.join("\u0000")),
  );
  return { vertices, facets };
}

function complexConnected(complex: SymbolicFiniteSimplicialComplex): boolean {
  if (complex.vertices.length === 0) return false;
  if (complex.vertices.length === 1) return true;
  const adjacency = new Map(
    complex.vertices.map((vertex) => [vertex, new Set<string>()]),
  );
  for (const facet of complex.facets) {
    for (const left of facet) {
      for (const right of facet) {
        if (left !== right) adjacency.get(left)?.add(right);
      }
    }
  }
  const visited = new Set<string>();
  const queue = [complex.vertices[0]];
  for (let cursor = 0; cursor < queue.length; cursor += 1) {
    const vertex = queue[cursor];
    if (visited.has(vertex)) continue;
    visited.add(vertex);
    for (const neighbor of adjacency.get(vertex) ?? []) {
      if (!visited.has(neighbor)) queue.push(neighbor);
    }
  }
  return visited.size === complex.vertices.length;
}

function nonemptyFaces(complex: SymbolicFiniteSimplicialComplex): Set<string> {
  const faces = new Set<string>();
  for (const facet of complex.facets) {
    const visit = (index: number, face: string[]) => {
      if (index === facet.length) {
        if (face.length > 0) faces.add([...face].sort().join("\u0000"));
        return;
      }
      visit(index + 1, face);
      face.push(facet[index]);
      visit(index + 1, face);
      face.pop();
    };
    visit(0, []);
  }
  return faces;
}

/** Verify a supplied elementary-collapse sequence; replay flags are ignored. */
function replayCollapsibilityWitness(
  complex: SymbolicFiniteSimplicialComplex,
  supplied: SymbolicCollapsibilityResult | undefined,
): SymbolicCollapsibilityResult | undefined {
  if (supplied === undefined) return undefined;
  if (supplied.status !== "collapsible") return deepFreeze({ ...supplied });
  if (supplied.collapseSequence === undefined) {
    return deepFreeze({
      status: "unknown",
      reason:
        "A collapsible assertion without an elementary-collapse sequence is diagnostic only.",
    });
  }
  const faces = nonemptyFaces(complex);
  const failures: string[] = [];
  for (const [index, step] of supplied.collapseSequence.entries()) {
    const freeFace = [...new Set(step.freeFace)].sort();
    const coface = [...new Set(step.coface)].sort();
    const freeKey = freeFace.join("\u0000");
    const cofaceKey = coface.join("\u0000");
    if (
      freeFace.length === 0 ||
      coface.length <= freeFace.length ||
      !freeFace.every((vertex) => coface.includes(vertex)) ||
      !faces.has(freeKey) ||
      !faces.has(cofaceKey)
    ) {
      failures.push(
        `Collapse ${index} is not a present free-face/coface pair.`,
      );
      continue;
    }
    const maximalContaining = [...faces].filter((candidateKey) => {
      const candidate = candidateKey.split("\u0000");
      if (!freeFace.every((vertex) => candidate.includes(vertex))) return false;
      return ![...faces].some((otherKey) => {
        const other = otherKey.split("\u0000");
        return (
          other.length > candidate.length &&
          candidate.every((vertex) => other.includes(vertex))
        );
      });
    });
    if (maximalContaining.length !== 1 || maximalContaining[0] !== cofaceKey) {
      failures.push(`Collapse ${index} does not use a free face.`);
      continue;
    }
    for (const candidateKey of [...faces]) {
      const candidate = candidateKey.split("\u0000");
      if (
        freeFace.every((vertex) => candidate.includes(vertex)) &&
        candidate.every((vertex) => coface.includes(vertex))
      ) {
        faces.delete(candidateKey);
      }
    }
  }
  const remainingVertices = [...faces].filter(
    (faceKey) => !faceKey.includes("\u0000"),
  );
  if (faces.size !== 1 || remainingVertices.length !== 1) {
    failures.push("The collapse sequence does not end at one vertex.");
  }
  if (failures.length > 0) {
    return deepFreeze({
      status: "unknown",
      reason: failures.join(" "),
      collapseSequence: supplied.collapseSequence,
    });
  }
  return deepFreeze({
    status: "collapsible",
    certificateHash: scientificSha256({
      complex,
      sequence: supplied.collapseSequence,
    }),
    replayPassed: true,
    collapseSequence: supplied.collapseSequence,
  });
}

/** Build every directed link from complete vertex-orbit representatives. */
export function certifyExactSymbolicDirectedLinks(
  cover: SymbolicRegularKernelCover,
  coorientation: SymmetryRestrictedWallCoorientation,
  schreier: ExactSymbolicSchreierHomomorphismCertificate,
  pullingMorse: ExactSymbolicPullingMorseCertificate,
  source: ExactSymbolicLinkOrbitCatalogue | ExactSymbolicDirectedLinkOracle,
  options: SymbolicLinkCertificationOptions = {},
): ExactSymbolicDirectedLinkCertificate {
  const failures: string[] = [];
  const coorientationHash = symbolicCoorientationDigest(coorientation);
  if (!("recompute" in source)) {
    failures.push(
      "Assertion-only directed-link catalogues are diagnostic; exact certification requires executable recomputation from raw links and direction values.",
    );
    return deepFreeze({
      status: "incomplete",
      sourceCoverId: cover.id,
      coorientationHash,
      schreierCertificateHash: schreier.replayHash,
      pullingMorseCertificateHash: pullingMorse.replayHash,
      linkCatalogueHash: source.certificateHash,
      exhaustive: false,
      morseModel: "canonical-pulling-subdivision",
      vertexOrbits: [],
      allAscendingNonemptyConnected: false,
      allDescendingNonemptyConnected: false,
      collapsibilityComplete: false,
      failures,
      replayHash: scientificSha256({ diagnosticOnly: source }),
    });
  }
  if (
    !hasVerifierBrand(schreier, VERIFIED_SCHREIER) ||
    !hasVerifierBrand(pullingMorse, VERIFIED_PULLING_MORSE)
  ) {
    failures.push(
      "Schreier and pulling-Morse inputs must be replayed verifiers.",
    );
  }
  let raw: ExactSymbolicDirectedLinkRawData;
  try {
    raw = source.recompute({
      cover,
      coorientation,
      schreier,
      pullingMorse,
    });
  } catch (error) {
    failures.push(
      `The directed-link oracle did not complete: ${error instanceof Error ? error.message : String(error)}.`,
    );
    raw = {
      exhaustive: false,
      representatives: [],
      vertexOrbitAction: {
        method: `${source.method}:failed`,
        objectKeys: [],
        generatorIds: [],
        transitions: [],
      },
    };
  }
  let orbitPartition: ExactOrbitPartitionReplay | undefined;
  try {
    orbitPartition = replayExactOrbitPartition(raw.vertexOrbitAction);
    validateOrbitPartitionReplay(
      orbitPartition,
      raw.representatives
        .map((representative) => representative.vertexKey)
        .sort(),
      "Link vertex orbit",
      failures,
    );
    validateOrbitActionObjects(
      orbitPartition,
      raw.representatives.map((representative) => representative.vertexKey),
      "Link vertex orbit",
      failures,
    );
  } catch (error) {
    if (error instanceof SymbolicRegularCoverError)
      failures.push(...error.errors);
    else throw error;
  }
  const linkCatalogueHash = scientificSha256({ method: source.method, raw });
  const vertexCount = exactIntegerToBigInt(cover.vertexOrbit.vertexCount);
  let representedVertexCount = 0n;
  let collapsibilityComplete = options.checkCollapsibility !== undefined;
  const seenRepresentatives = new Set<string>();
  const seenVertexKeys = new Set<string>();
  const vertexOrbits: SymbolicDirectedLinkRecord[] = [];
  for (const representative of raw.representatives) {
    if (seenRepresentatives.has(representative.id)) {
      failures.push(`Link representative ${representative.id} repeats.`);
      continue;
    }
    seenRepresentatives.add(representative.id);
    if (seenVertexKeys.has(representative.vertexKey)) {
      failures.push(`Link vertex key ${representative.vertexKey} repeats.`);
      continue;
    }
    seenVertexKeys.add(representative.vertexKey);
    try {
      representedVertexCount += positiveExactInteger(
        representative.representedVertexCount,
        `${representative.id} represented vertex count`,
      );
    } catch (error) {
      if (error instanceof SymbolicRegularCoverError)
        failures.push(...error.errors);
      else throw error;
    }
    const full = canonicalizeComplex(
      representative.fullLink,
      `${representative.id} full link`,
      failures,
    );
    const directionByVertex = new Map<string, bigint>();
    for (const direction of representative.directions) {
      if (directionByVertex.has(direction.vertexId)) {
        failures.push(
          `${representative.id} repeats direction ${direction.vertexId}.`,
        );
        continue;
      }
      try {
        const value = signedIntegerToBigInt(
          direction.value,
          `${representative.id}:${direction.vertexId} direction`,
        );
        if (value === 0n) {
          failures.push(
            `${representative.id}:${direction.vertexId} has level value zero.`,
          );
        }
        directionByVertex.set(direction.vertexId, value);
      } catch (error) {
        if (error instanceof SymbolicRegularCoverError)
          failures.push(...error.errors);
        else throw error;
      }
    }
    for (const vertex of full.vertices) {
      if (!directionByVertex.has(vertex)) {
        failures.push(`${representative.id} has no direction for ${vertex}.`);
      }
    }
    for (const vertex of directionByVertex.keys()) {
      if (!full.vertices.includes(vertex)) {
        failures.push(
          `${representative.id} has a direction for unknown ${vertex}.`,
        );
      }
    }
    const ascending = inducedComplex(
      full,
      new Set(
        [...directionByVertex.entries()]
          .filter(([, value]) => value > 0n)
          .map(([vertex]) => vertex),
      ),
    );
    const descending = inducedComplex(
      full,
      new Set(
        [...directionByVertex.entries()]
          .filter(([, value]) => value < 0n)
          .map(([vertex]) => vertex),
      ),
    );
    const ascendingCollapsibility = replayCollapsibilityWitness(
      ascending,
      options.checkCollapsibility?.(ascending, {
        representativeId: representative.id,
        kind: "ascending",
      }),
    );
    const descendingCollapsibility = replayCollapsibilityWitness(
      descending,
      options.checkCollapsibility?.(descending, {
        representativeId: representative.id,
        kind: "descending",
      }),
    );
    for (const result of [ascendingCollapsibility, descendingCollapsibility]) {
      if (
        result === undefined ||
        result.status === "unknown" ||
        result.replayPassed !== true ||
        !isScientificSha256(result.certificateHash)
      ) {
        collapsibilityComplete = false;
      }
    }
    vertexOrbits.push({
      representativeId: representative.id,
      vertexKey: representative.vertexKey,
      representedVertexCount: representative.representedVertexCount,
      ascending: {
        complex: ascending,
        nonempty: ascending.vertices.length > 0,
        connected: complexConnected(ascending),
        ...(ascendingCollapsibility === undefined
          ? {}
          : { collapsibility: ascendingCollapsibility }),
      },
      descending: {
        complex: descending,
        nonempty: descending.vertices.length > 0,
        connected: complexConnected(descending),
        ...(descendingCollapsibility === undefined
          ? {}
          : { collapsibility: descendingCollapsibility }),
      },
    });
  }
  if (raw.exhaustive && representedVertexCount !== vertexCount) {
    failures.push(
      `Link representatives cover ${representedVertexCount} vertices; expected ${vertexCount}.`,
    );
  }
  const allAscendingNonemptyConnected = vertexOrbits.every(
    (entry) => entry.ascending.nonempty && entry.ascending.connected,
  );
  const allDescendingNonemptyConnected = vertexOrbits.every(
    (entry) => entry.descending.nonempty && entry.descending.connected,
  );
  if (!allAscendingNonemptyConnected) {
    failures.push("At least one ascending link is empty or disconnected.");
  }
  if (!allDescendingNonemptyConnected) {
    failures.push("At least one descending link is empty or disconnected.");
  }
  const status =
    failures.length > 0
      ? "failed"
      : raw.exhaustive && orbitPartition !== undefined
        ? "passed"
        : "incomplete";
  const replayHash = scientificSha256({
    coverId: cover.id,
    coorientationHash,
    schreierCertificateHash: schreier.replayHash,
    pullingMorseCertificateHash: pullingMorse.replayHash,
    linkCatalogueHash,
    vertexOrbits,
  });
  const result: ExactSymbolicDirectedLinkCertificate = {
    status,
    sourceCoverId: cover.id,
    coorientationHash,
    schreierCertificateHash: schreier.replayHash,
    pullingMorseCertificateHash: pullingMorse.replayHash,
    linkCatalogueHash,
    exhaustive: raw.exhaustive,
    morseModel: "canonical-pulling-subdivision",
    vertexOrbits,
    allAscendingNonemptyConnected,
    allDescendingNonemptyConnected,
    collapsibilityComplete,
    failures,
    replayHash,
  };
  return status === "passed"
    ? attachVerifierBrand(result, VERIFIED_LINKS)
    : deepFreeze(result);
}

/**
 * Promote a symbolic orbit computation only after every finite catalogue and
 * replay certificate closes. Symmetry restricts how the solution was found;
 * it does not weaken a positive solution transported to every actual wall.
 */
export function certifySymbolicRegularKernelFibering(
  cover: SymbolicRegularKernelCover,
  input: SymbolicRegularKernelFiberingPromotionInput,
): SymbolicRegularKernelFiberingPromotionResult {
  const blockers: string[] = [];
  const {
    wallCatalogue,
    wallSpace,
    search,
    boundaryCatalogue,
    cocycle,
    schreier,
    pullingMorse,
    links,
  } = input;
  const solution = search.solution;
  const coorientationHash =
    solution === undefined ? undefined : symbolicCoorientationDigest(solution);
  if (!hasVerifierBrand(cover, VERIFIED_SYMBOLIC_COVER)) {
    blockers.push(
      "The symbolic cover was imported without replaying its verifier.",
    );
  }
  if (
    cover.scientificSourceBinding === undefined ||
    !Object.values(cover.scientificSourceBinding.checks).every(Boolean) ||
    !isScientificSha256(cover.scientificSourceBinding.sourceSystemSha256) ||
    !isScientificSha256(cover.scientificSourceBinding.sphericalPlanSha256) ||
    !isScientificSha256(cover.scientificSourceBinding.replayHash) ||
    !isScientificSha256(cover.deckGroup.certificateHash) ||
    !Object.values(cover.certificate.checks).every(Boolean)
  ) {
    blockers.push(
      "The deck group, full Coxeter source, and spherical plan lack replayed SHA-256 bindings.",
    );
  }
  if (
    !hasVerifierBrand(wallCatalogue, VERIFIED_WALL_CATALOGUE) ||
    !hasVerifierBrand(wallSpace, VERIFIED_WALL_SPACE) ||
    !hasVerifierBrand(boundaryCatalogue, VERIFIED_BOUNDARY_CATALOGUE) ||
    !hasVerifierBrand(search, VERIFIED_COORIENTATION_SEARCH) ||
    !hasVerifierBrand(cocycle, VERIFIED_COCYCLE) ||
    !hasVerifierBrand(schreier, VERIFIED_SCHREIER) ||
    !hasVerifierBrand(pullingMorse, VERIFIED_PULLING_MORSE) ||
    !hasVerifierBrand(links, VERIFIED_LINKS)
  ) {
    blockers.push(
      "One or more imported certificate objects were not replayed by their runtime verifier.",
    );
  }
  if (
    wallCatalogue.sourceCoverId !== cover.id ||
    !wallCatalogue.exhaustive ||
    !isScientificSha256(wallCatalogue.sourceIncidenceHash) ||
    !isScientificSha256(wallCatalogue.orbitPartitionReplayHash) ||
    !isScientificSha256(wallCatalogue.certificateHash) ||
    !Object.values(wallCatalogue.checks).every((value) => value === true)
  ) {
    blockers.push(
      "The exact quotient-wall orbit catalogue is stale or incomplete.",
    );
  }
  if (
    !wallCatalogue.wallOrbits.every(
      (wall) => wall.twoSided && wall.sideStabilizerPreserving,
    ) ||
    wallCatalogue.checks.twoSidednessVerified !== true ||
    wallCatalogue.checks.sideTransportVerified !== true
  ) {
    blockers.push(
      "Two-sidedness and exact side transport have not both replayed.",
    );
  }
  if (
    wallSpace.sourceCoverId !== cover.id ||
    wallSpace.wallCatalogueHash !== wallCatalogue.certificateHash ||
    !wallSpace.exactWithinRestrictedSpace ||
    !isScientificSha256(wallSpace.partitionCertificateHash) ||
    !isScientificSha256(wallSpace.symmetry.certificate.certificateHash) ||
    !wallSpace.variables.every((variable) =>
      isScientificSha256(variable.sideTransportCertificateHash),
    )
  ) {
    blockers.push("The symmetry wall space is stale or incomplete.");
  }
  if (
    search.status !== "solution-found" ||
    search.unrestrictedConclusion !== "existence-certified" ||
    solution === undefined ||
    !solution.valid
  ) {
    blockers.push(
      "No exact transported coorientation was found; restricted-search failure remains inconclusive.",
    );
  }
  if (
    boundaryCatalogue.sourceCoverId !== cover.id ||
    boundaryCatalogue.wallSpaceHash !== symbolicWallSpaceDigest(wallSpace) ||
    !boundaryCatalogue.exhaustive ||
    !Object.values(boundaryCatalogue.checks).every(Boolean) ||
    cocycle.status !== "passed" ||
    !cocycle.exhaustive ||
    cocycle.failures.length > 0 ||
    !cocycle.checks.every((check) => check.passed) ||
    cocycle.boundaryCatalogueHash !== boundaryCatalogue.certificateHash ||
    cocycle.replayHash !== search.cocycle?.replayHash ||
    cocycle.coorientationHash !== coorientationHash
  ) {
    blockers.push(
      "The complete cellular cocycle orbit catalogue did not replay.",
    );
  }
  if (
    schreier.sourceCoverId !== cover.id ||
    schreier.coorientationHash !== coorientationHash ||
    schreier.status !== "passed" ||
    !schreier.exhaustive ||
    !schreier.normalizedMapPrimitive ||
    schreier.failures.length > 0 ||
    !Object.values(schreier.checks).every(Boolean)
  ) {
    blockers.push(
      "A complete primitive Reidemeister-Schreier character is missing.",
    );
  }
  if (
    pullingMorse.sourceCoverId !== cover.id ||
    pullingMorse.coorientationHash !== coorientationHash ||
    pullingMorse.schreierCertificateHash !== schreier.replayHash ||
    pullingMorse.status !== "passed" ||
    !pullingMorse.exhaustive ||
    pullingMorse.failures.length > 0 ||
    !Object.values(pullingMorse.checks).every(Boolean) ||
    !isScientificSha256(pullingMorse.replayHash)
  ) {
    blockers.push(
      "The exact pulling-subdivision PL Morse model did not replay.",
    );
  }
  if (
    links.sourceCoverId !== cover.id ||
    links.coorientationHash !== coorientationHash ||
    links.schreierCertificateHash !== schreier.replayHash ||
    links.pullingMorseCertificateHash !== pullingMorse.replayHash ||
    links.status !== "passed" ||
    !links.exhaustive ||
    links.failures.length > 0 ||
    !links.allAscendingNonemptyConnected ||
    !links.allDescendingNonemptyConnected ||
    links.morseModel !== "canonical-pulling-subdivision"
  ) {
    blockers.push(
      "The complete canonical-subdivision ascending/descending link replay did not pass.",
    );
  }
  if (blockers.length > 0 || coorientationHash === undefined) {
    return {
      status: "blocked",
      sourceCoverId: cover.id,
      blockers,
      claim: "none",
      restrictedSearchFailureConclusion: "inconclusive",
    };
  }

  const base = baseCompletenessScope();
  const completeness: SymbolicRegularCoverCompletenessScope = {
    ...base,
    exactClaims: [
      ...base.exactClaims,
      "symmetry-restricted-wall-search",
      "virtual-algebraic-fibering",
      "finitely-generated-fibering-kernel",
    ],
    wallSearch: {
      kind: "symmetry-restricted",
      symmetrySubgroupId: wallSpace.symmetry.id,
      exhaustiveWithinRestrictedSpace: search.exhaustiveWithinRestrictedSpace,
      exhaustiveWithoutSymmetryRestriction: false,
    },
    promotionGate: {
      cellRepresentation: "complete-exact-cell-orbit-catalogue",
      sourceAndSphericalPlanBound: true,
      completeCellOrbitCatalogue: true,
      allQuotientWallsEnumerated: true,
      unrestrictedCoorientationSearch: false,
      coorientationExistenceCertified: true,
      primitiveEpimorphismCertified: true,
      allAscendingDescendingLinksChecked: true,
      positiveWitnessVerified: true,
    },
    prohibitedClaims: [
      {
        claim: "unrestricted-wall-search",
        reason:
          "Symmetry-restricted existence certifies the exported solution, not exhaustion of every independent wall sign.",
      },
    ],
  };
  const certificateHash = scientificSha256({
    coverId: cover.id,
    coorientationHash,
    wallCatalogueHash: wallCatalogue.certificateHash,
    boundaryCatalogueHash: boundaryCatalogue.certificateHash,
    cocycleHash: cocycle.replayHash,
    schreierHash: schreier.replayHash,
    pullingMorseHash: pullingMorse.replayHash,
    linksHash: links.replayHash,
  });
  return {
    status: "passed",
    method: "exact-symbolic-orbit-replay",
    sourceCoverId: cover.id,
    coorientationHash,
    wallCatalogueHash: wallCatalogue.certificateHash,
    cellBoundaryCatalogueHash: boundaryCatalogue.certificateHash,
    schreierCertificateHash: schreier.replayHash,
    pullingMorseCertificateHash: pullingMorse.replayHash,
    linkCertificateHash: links.replayHash,
    checks: {
      exactRegularKernelCover: true,
      completeWallOrbitCatalogue: true,
      wallsTwoSidedWithExactSideTransport: true,
      restrictedCoorientationProvidesGlobalSolution: true,
      completeCellOrbitCocycleReplay: true,
      primitiveEpimorphismCertified: true,
      exactPullingMorseModelReplayed: true,
      completeDirectedLinkOrbitReplay: true,
      ascendingDescendingLinksNonemptyConnected: true,
    },
    completeness,
    certificateHash,
    claims: [
      "virtual-algebraic-fibering",
      "finitely-generated-fibering-kernel",
    ],
    caveats: [
      "The coorientation was discovered in a symmetry-restricted subspace; the exported transported signs nevertheless define a wall sign on the complete quotient.",
      ...(links.collapsibilityComplete
        ? []
        : [
            "Collapsibility was not completely certified. It is not used for the finite-generation claim recorded here.",
          ]),
    ],
  };
}

/**
 * Enforce the model's claim boundary at runtime.
 *
 * A positive restricted witness may certify existence after every global orbit
 * and PL Morse replay passes. Exhausting the restricted space without finding
 * one remains inconclusive about unrestricted wall signs.
 */
export function assertSymbolicRegularCoverClaimAllowed(
  scope: SymbolicRegularCoverCompletenessScope,
  claim: SymbolicRegularCoverClaim,
): void {
  if (!scope.exactClaims.includes(claim)) {
    const prohibition = scope.prohibitedClaims.find(
      (entry) => entry.claim === claim,
    );
    throw new SymbolicRegularCoverError("Claim exceeds symbolic completeness", [
      prohibition?.reason ?? `${claim} is outside this model's exact scope.`,
    ]);
  }
}
