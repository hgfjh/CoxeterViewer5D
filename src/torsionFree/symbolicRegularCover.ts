function attachVerifierBrand<T extends object>(value: T, brand: symbol): T {
  Object.defineProperty(value, brand, {
    value: true,
    enumerable: false,
    configurable: false,
    writable: false,
  });
  return deepFreeze(value);
}

function deepFreeze<T>(value: T): T {
  if (value === null || typeof value !== "object" || Object.isFrozen(value)) {
    return value;
  }
  for (const child of Object.values(value)) deepFreeze(child);
  return Object.freeze(value);
}

function hasVerifierBrand(value: object, brand: symbol): boolean {
  return Object.prototype.hasOwnProperty.call(value, brand);
}

/**
 * Rebuild an exact finite orbit partition from a complete action table.
 * Invalid or incomplete tables are rejected before a verifier brand is minted.
 */
export function replayExactOrbitPartition(
  input: ExactOrbitActionReplayInput,
): ExactOrbitPartitionReplay {
  const errors: string[] = [];
  const objectKeys = [...input.objectKeys];
  const canonicalObjectKeys = [...new Set(objectKeys)].sort();
  const generatorIds = [...input.generatorIds];
  const canonicalGeneratorIds = [...new Set(generatorIds)].sort();
  if (
    objectKeys.length !== canonicalObjectKeys.length ||
    objectKeys.some((key, index) => key !== canonicalObjectKeys[index])
  ) {
    errors.push("Orbit action object keys must be unique and sorted.");
  }
  if (
    generatorIds.length !== canonicalGeneratorIds.length ||
    generatorIds.some((key, index) => key !== canonicalGeneratorIds[index])
  ) {
    errors.push("Orbit action generator ids must be unique and sorted.");
  }
  const objectSet = new Set(canonicalObjectKeys);
  const generatorSet = new Set(canonicalGeneratorIds);
  const transitionByPair = new Map<
    string,
    { targetKey: string; sideSign: SymbolicOrientationSign }
  >();
  for (const transition of input.transitions) {
    if (!objectSet.has(transition.sourceKey)) {
      errors.push(`Unknown orbit-action source ${transition.sourceKey}.`);
    }
    if (!objectSet.has(transition.targetKey)) {
      errors.push(`Unknown orbit-action target ${transition.targetKey}.`);
    }
    if (!generatorSet.has(transition.generatorId)) {
      errors.push(`Unknown orbit-action generator ${transition.generatorId}.`);
    }
    const pairKey = `${transition.sourceKey}\u0000${transition.generatorId}`;
    if (transitionByPair.has(pairKey)) {
      errors.push(
        `Orbit action repeats ${transition.generatorId} at ${transition.sourceKey}.`,
      );
      continue;
    }
    transitionByPair.set(pairKey, {
      targetKey: transition.targetKey,
      sideSign: transition.sideSign ?? 1,
    });
  }
  for (const generatorId of canonicalGeneratorIds) {
    const targets = new Set<string>();
    for (const sourceKey of canonicalObjectKeys) {
      const transition = transitionByPair.get(
        `${sourceKey}\u0000${generatorId}`,
      );
      if (transition === undefined) {
        errors.push(`Orbit action omits ${generatorId} at ${sourceKey}.`);
        continue;
      }
      targets.add(transition.targetKey);
    }
    if (targets.size !== canonicalObjectKeys.length) {
      errors.push(`${generatorId} does not act bijectively on the object set.`);
    }
  }
  if (errors.length > 0) {
    throw new SymbolicRegularCoverError(
      "Cannot replay exact orbit partition",
      errors,
    );
  }

  const adjacency = new Map(
    canonicalObjectKeys.map((key) => [key, new Set<string>()]),
  );
  for (const [pairKey, transition] of transitionByPair) {
    const sourceKey = pairKey.slice(0, pairKey.indexOf("\u0000"));
    adjacency.get(sourceKey)?.add(transition.targetKey);
    adjacency.get(transition.targetKey)?.add(sourceKey);
  }
  const canonicalRepresentativeKeys: string[] = [];
  const transportSide = new Map<string, SymbolicOrientationSign>();
  let stabilizerLoopCount = 0;
  let sideTransportConsistent = true;
  const visited = new Set<string>();
  for (const seed of canonicalObjectKeys) {
    if (visited.has(seed)) continue;
    const component: string[] = [];
    const queue = [seed];
    visited.add(seed);
    for (let cursor = 0; cursor < queue.length; cursor += 1) {
      const sourceKey = queue[cursor];
      component.push(sourceKey);
      for (const targetKey of adjacency.get(sourceKey) ?? []) {
        if (!visited.has(targetKey)) {
          visited.add(targetKey);
          queue.push(targetKey);
        }
      }
    }
    component.sort();
    const representative = component[0];
    canonicalRepresentativeKeys.push(representative);
    const sideQueue = [representative];
    transportSide.set(representative, 1);
    for (let cursor = 0; cursor < sideQueue.length; cursor += 1) {
      const sourceKey = sideQueue[cursor];
      const sourceSide = transportSide.get(sourceKey) ?? 1;
      for (const generatorId of canonicalGeneratorIds) {
        const transition = transitionByPair.get(
          `${sourceKey}\u0000${generatorId}`,
        );
        if (transition === undefined) continue;
        const targetSide = (sourceSide * transition.sideSign) as 1 | -1;
        const knownSide = transportSide.get(transition.targetKey);
        if (knownSide === undefined) {
          transportSide.set(transition.targetKey, targetSide);
          sideQueue.push(transition.targetKey);
        } else {
          stabilizerLoopCount += 1;
          if (knownSide !== targetSide) sideTransportConsistent = false;
        }
      }
    }
  }
  canonicalRepresentativeKeys.sort();
  const checks = {
    representativesCanonical: true,
    stabilizersReplayed: true,
    transportsReplayed: true,
    pairwiseDisjoint: true,
    coversEveryObject: visited.size === canonicalObjectKeys.length,
  };
  if (!checks.coversEveryObject || !sideTransportConsistent) {
    throw new SymbolicRegularCoverError("Cannot replay exact orbit partition", [
      ...(!checks.coversEveryObject
        ? ["Orbit traversal did not cover every supplied object."]
        : []),
      ...(!sideTransportConsistent
        ? ["A stabilizer loop reverses the transported wall side."]
        : []),
    ]);
  }
  const replay = attachVerifierBrand(
    {
      status: "passed" as const,
      method: input.method,
      canonicalRepresentativeKeys,
      checks,
      replayHash: scientificSha256({
        method: input.method,
        objectKeys: canonicalObjectKeys,
        generatorIds: canonicalGeneratorIds,
        transitions: [...input.transitions].sort((left, right) =>
          `${left.sourceKey}\u0000${left.generatorId}\u0000${left.targetKey}`.localeCompare(
            `${right.sourceKey}\u0000${right.generatorId}\u0000${right.targetKey}`,
          ),
        ),
        canonicalRepresentativeKeys,
        stabilizerLoopCount,
        sideTransportConsistent,
      }),
    },
    VERIFIED_ORBIT_PARTITION,
  );
  verifiedOrbitPartitionFacts.set(replay, {
    objectKeys: canonicalObjectKeys,
    generatorIds: canonicalGeneratorIds,
    stabilizerLoopCount,
    sideTransportConsistent,
  });
  return replay;
}

/** Archival SHA-256 binding for the complete Coxeter presentation data. */
export function symbolicCoxeterMatrixDigest(
  system: Pick<CoxeterSystemInput, "rank" | "generators" | "coxeterMatrix">,
): string {
  return scientificSha256({
    rank: system.rank,
    generators: system.generators.map((generator) => ({
      id: generator.id,
      label: generator.label,
    })),
    coxeterMatrix: system.coxeterMatrix,
  });
}

function positiveExactInteger(value: ExactIntegerValue, label: string): bigint {
  if (!/^[1-9][0-9]*$/.test(value.decimal)) {
    throw new SymbolicRegularCoverError("Invalid exact integer", [
      `${label} must be a positive canonical decimal integer.`,
    ]);
  }
  const exact = exactIntegerToBigInt(value);
  if (
    value.safeInteger !== undefined &&
    (!Number.isSafeInteger(value.safeInteger) ||
      BigInt(value.safeInteger) !== exact)
  ) {
    throw new SymbolicRegularCoverError("Invalid exact integer", [
      `${label}.safeInteger does not equal ${value.decimal}.`,
    ]);
  }
  return exact;
}

function sameElement<Element>(
  oracle: ExactDeckGroupOracle<Element>,
  left: Element,
  right: Element,
): boolean {
  return oracle.key(left) === oracle.key(right);
}

function power<Element>(
  oracle: ExactDeckGroupOracle<Element>,
  element: Element,
  exponent: number,
): Element {
  let result = oracle.identity;
  for (let index = 0; index < exponent; index += 1) {
    result = oracle.multiply(result, element);
  }
  return result;
}

function enumerateGeneratedSubgroupOrder<Element>(
  oracle: ExactDeckGroupOracle<Element>,
  generators: readonly Element[],
  expectedOrder: bigint,
  maxOrder: number,
  label: string,
): bigint {
  if (expectedOrder > BigInt(maxOrder)) {
    throw new SymbolicRegularCoverError(
      "Spherical image needs an exact order routine",
      [
        `${label} has expected order ${expectedOrder}; the fallback enumeration cap is ${maxOrder}.`,
      ],
    );
  }
  const identityKey = oracle.key(oracle.identity);
  const elements = new Map<string, Element>([[identityKey, oracle.identity]]);
  const queue = [oracle.identity];
  for (let cursor = 0; cursor < queue.length; cursor += 1) {
    const current = queue[cursor];
    for (const generator of generators) {
      const next = oracle.multiply(current, generator);
      const key = oracle.key(next);
      if (key.length === 0) {
        throw new SymbolicRegularCoverError("Invalid exact deck-group key", [
          `${label} produced an empty element key.`,
        ]);
      }
      if (!elements.has(key)) {
        elements.set(key, next);
        queue.push(next);
        if (BigInt(elements.size) > expectedOrder) {
          return BigInt(elements.size);
        }
      }
    }
  }
  return BigInt(elements.size);
}

function subgroupImageOrder<Element>(
  oracle: ExactDeckGroupOracle<Element>,
  subgroup: SphericalSpecialSubgroupPlan,
  maxEnumeratedOrder: number,
): { order: bigint; method: "exact-oracle" | "exact-enumeration" } {
  const generators = subgroup.generators.map(
    (generator) => oracle.generatorImages[generator],
  );
  if (oracle.subgroupOrder !== undefined) {
    return {
      order: positiveExactInteger(
        oracle.subgroupOrder(generators),
        `${subgroup.id} image order`,
      ),
      method: "exact-oracle",
    };
  }
  const expectedOrder = positiveExactInteger(
    subgroup.order,
    `${subgroup.id} spherical order`,
  );
  return {
    order: enumerateGeneratedSubgroupOrder(
      oracle,
      generators,
      expectedOrder,
      maxEnumeratedOrder,
      subgroup.id,
    ),
    method: "exact-enumeration",
  };
}

function isProperSubset(left: readonly number[], right: readonly number[]) {
  if (left.length >= right.length) return false;
  const rightSet = new Set(right);
  return left.every((generator) => rightSet.has(generator));
}

