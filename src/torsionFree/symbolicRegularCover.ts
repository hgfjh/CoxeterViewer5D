/**
 * Build exact orbit descriptors for H\Sigma when H is a certified regular
 * kernel. The implementation enumerates only finite spherical images, never Q.
 */
export function buildSymbolicRegularKernelCover<Element>(
  input: unknown,
  deckGroup: ExactDeckGroupOracle<Element>,
  sphericalPlan: SphericalSubsetPlan,
  options: BuildSymbolicRegularCoverOptions = {},
): SymbolicRegularKernelCover {
  const system = parseCoxeterSystemInput(input);
  const errors: string[] = [];
  const sourceDigest = symbolicCoxeterMatrixDigest(system);
  const sourceSystemSha256 = scientificSha256(system);
  const sphericalPlanSha256 = scientificSha256(sphericalPlan);
  const sphericalPlanSourceBinding = options.sphericalPlanSourceBinding;
  const sphericalPlanSourceBound =
    sphericalPlanSourceBinding !== undefined &&
    sphericalPlanSourceBinding.sourceSystemSha256 === sourceSystemSha256 &&
    sphericalPlanSourceBinding.sphericalPlanSha256 === sphericalPlanSha256 &&
    Object.values(sphericalPlanSourceBinding.checks).every(Boolean) &&
    isScientificSha256(sphericalPlanSourceBinding.replayHash);
  if (sphericalPlanSourceBinding !== undefined && !sphericalPlanSourceBound) {
    errors.push(
      "The spherical-subset plan source binding is stale, incomplete, or not SHA-256 replay evidence.",
    );
  }
  const certificate = deckGroup.certificate;
  const certificateChecks = Object.entries(certificate.checks)
    .filter(([, passed]) => !passed)
    .map(([check]) => check);
  if (deckGroup.id !== certificate.deckGroupId) {
    errors.push("The exact oracle id does not match its certificate.");
  }
  if (
    certificate.sourceSystem.name !== system.name ||
    certificate.sourceSystem.rank !== system.rank ||
    certificate.sourceSystem.coxeterMatrixDigest !== sourceDigest
  ) {
    errors.push(
      "The deck-group certificate is bound to another Coxeter system.",
    );
  }
  if (certificateChecks.length > 0) {
    errors.push(
      `Deck-group certificate checks did not pass: ${certificateChecks.join(", ")}.`,
    );
  }
  if (!isScientificSha256(certificate.certificateHash)) {
    errors.push("The deck-group certificate must carry a SHA-256 hash.");
  }

  let deckOrder = 0n;
  let closureOrder = 0n;
  try {
    deckOrder = positiveExactInteger(
      certificate.groupOrder,
      "deck-group order",
    );
    closureOrder = positiveExactInteger(
      certificate.generatorClosureOrder,
      "generator-closure order",
    );
  } catch (error) {
    if (error instanceof SymbolicRegularCoverError) {
      errors.push(...error.errors);
    } else {
      throw error;
    }
  }
  if (deckOrder !== closureOrder) {
    errors.push(
      `Generator closure has order ${closureOrder}; the certified deck group has order ${deckOrder}.`,
    );
  }
  if (deckGroup.generatorImages.length !== system.rank) {
    errors.push(
      `The oracle supplies ${deckGroup.generatorImages.length} generator images; expected ${system.rank}.`,
    );
  }
  if (
    sphericalPlan.status !== "complete" ||
    sphericalPlan.rank !== system.rank
  ) {
    errors.push(
      "The symbolic regular cover requires a complete spherical-subset plan for the same rank.",
    );
  }

  const identityKey = deckGroup.key(deckGroup.identity);
  if (identityKey.trim().length === 0) {
    errors.push("The exact deck-group identity has an empty canonical key.");
  }
  const generatorInvolutions = Array.from(
    { length: Math.min(system.rank, deckGroup.generatorImages.length) },
    (_unused, generator) => {
      const image = deckGroup.generatorImages[generator];
      const leftIdentity = deckGroup.multiply(deckGroup.identity, image);
      const rightIdentity = deckGroup.multiply(image, deckGroup.identity);
      const inverse = deckGroup.inverse(image);
      const square = deckGroup.multiply(image, image);
      const passed =
        sameElement(deckGroup, leftIdentity, image) &&
        sameElement(deckGroup, rightIdentity, image) &&
        sameElement(deckGroup, inverse, image) &&
        sameElement(deckGroup, square, deckGroup.identity);
      if (!passed) {
        errors.push(`Generator ${generator} is not an exact involution in Q.`);
      }
      return passed;
    },
  );

  let finiteRelationsPassed = true;
  if (deckGroup.generatorImages.length === system.rank) {
    for (let left = 0; left < system.rank; left += 1) {
      for (let right = left + 1; right < system.rank; right += 1) {
        const m = system.coxeterMatrix[left][right];
        if (m === "inf") continue;
        const product = deckGroup.multiply(
          deckGroup.generatorImages[left],
          deckGroup.generatorImages[right],
        );
        if (
          !sameElement(
            deckGroup,
            power(deckGroup, product, m),
            deckGroup.identity,
          )
        ) {
          finiteRelationsPassed = false;
          errors.push(
            `The exact images do not satisfy (s${left}s${right})^${m} = 1.`,
          );
        }
      }
    }
  } else {
    finiteRelationsPassed = false;
  }

  if (errors.length > 0) {
    throw new SymbolicRegularCoverError(
      "Cannot build the symbolic regular kernel cover",
      errors,
    );
  }

  const maxEnumeratedOrder =
    options.maxEnumeratedSphericalImageOrder ?? 1_000_000;
  if (!Number.isSafeInteger(maxEnumeratedOrder) || maxEnumeratedOrder < 1) {
    throw new SymbolicRegularCoverError("Invalid spherical enumeration cap", [
      "maxEnumeratedSphericalImageOrder must be a positive safe integer.",
    ]);
  }

  const sphericalCellOrbits: SymbolicSphericalCellOrbitDescriptor[] = [
    {
      id: "cell-orbit:T:empty",
      sphericalSubsetId: "T:empty",
      generators: [],
      generatorLabels: [],
      dimension: 0,
      sphericalSubgroupOrder: toExactIntegerValue(1n),
      sphericalImageOrder: toExactIntegerValue(1n),
      imageOrderMethod: "empty-subset",
      cellCount: toExactIntegerValue(deckOrder),
      deckOrbitCount: 1,
      deckAction: "left-multiplication",
      representative: {
        kind: "right-coset",
        baseDeckElementKey: identityKey,
        stabilizerGeneratorKeys: [],
      },
      exact: true,
    },
  ];

  for (const subgroup of sphericalPlan.sphericalSubgroups) {
    const subgroupOrder = positiveExactInteger(
      subgroup.order,
      `${subgroup.id} order`,
    );
    const image = subgroupImageOrder(deckGroup, subgroup, maxEnumeratedOrder);
    if (image.order !== subgroupOrder) {
      throw new SymbolicRegularCoverError(
        "The regular kernel meets a spherical special subgroup",
        [
          `${subgroup.id} has order ${subgroupOrder}, but its exact image has order ${image.order}.`,
        ],
      );
    }
    if (deckOrder % subgroupOrder !== 0n) {
      throw new SymbolicRegularCoverError(
        "Nonintegral spherical cell-orbit count",
        [
          `${subgroup.id} has order ${subgroupOrder}, which does not divide |Q| = ${deckOrder}.`,
        ],
      );
    }
    sphericalCellOrbits.push({
      id: `cell-orbit:${subgroup.id}`,
      sphericalSubsetId: subgroup.id,
      generators: [...subgroup.generators],
      generatorLabels: [...subgroup.generatorLabels],
      dimension: subgroup.rank,
      sphericalSubgroupOrder: toExactIntegerValue(subgroupOrder),
      sphericalImageOrder: toExactIntegerValue(image.order),
      imageOrderMethod: image.method,
      cellCount: toExactIntegerValue(deckOrder / subgroupOrder),
      deckOrbitCount: 1,
      deckAction: "left-multiplication",
      representative: {
        kind: "right-coset",
        baseDeckElementKey: identityKey,
        stabilizerGeneratorKeys: subgroup.generators.map((generator) =>
          deckGroup.key(deckGroup.generatorImages[generator]),
        ),
      },
      exact: true,
    });
  }

  sphericalCellOrbits.sort(
    (left, right) =>
      left.dimension - right.dimension ||
      left.sphericalSubsetId.localeCompare(right.sphericalSubsetId),
  );
  const sphericalFaceOrbits: SymbolicSphericalFaceOrbitDescriptor[] = [];
  for (const coface of sphericalCellOrbits) {
    const cofaceOrder = exactIntegerToBigInt(coface.sphericalSubgroupOrder);
    for (const face of sphericalCellOrbits) {
      if (!isProperSubset(face.generators, coface.generators)) continue;
      const faceOrder = exactIntegerToBigInt(face.sphericalSubgroupOrder);
      sphericalFaceOrbits.push({
        id: `face-orbit:${face.sphericalSubsetId}<${coface.sphericalSubsetId}`,
        faceOrbitId: face.id,
        cofaceOrbitId: coface.id,
        codimension: coface.dimension - face.dimension,
        facesPerCoface: toExactIntegerValue(cofaceOrder / faceOrder),
        exact: true,
      });
    }
  }

  const generatorTransitions = system.generators.map((generator, index) => {
    const rightFactorKey = deckGroup.key(deckGroup.generatorImages[index]);
    return {
      id: `transition:g${index}`,
      generator: index,
      generatorId: generator.id,
      generatorLabel: generator.label,
      rightFactorKey,
      source: { kind: "deck-element-parameter" as const, name: "q" as const },
      target: {
        kind: "right-product" as const,
        leftParameter: "q" as const,
        rightFactorKey,
      },
      involutive: true as const,
      exact: true as const,
    };
  });
  const id = `symbolic-kernel:${sourceDigest}:${certificate.certificateHash}`;
  const completeness = baseCompletenessScope();
  completeness.promotionGate.sourceAndSphericalPlanBound =
    sphericalPlanSourceBound;

  return attachVerifierBrand(
    {
      schemaVersion: 1,
      kind: "symbolic-regular-kernel-cover",
      id,
      systemName: system.name,
      systemRank: system.rank,
      coxeterMatrixDigest: sourceDigest,
      kernelIndex: toExactIntegerValue(deckOrder),
      deckGroup: {
        id: deckGroup.id,
        name: deckGroup.name,
        order: toExactIntegerValue(deckOrder),
        identityKey,
        generatorImageKeys: deckGroup.generatorImages.map((image) =>
          deckGroup.key(image),
        ),
        certificateMethod: certificate.method,
        certificateHash: certificate.certificateHash,
        ...(certificate.sourceHash === undefined
          ? {}
          : { sourceHash: certificate.sourceHash }),
      },
      vertexOrbit: {
        id: "vertex-orbit",
        vertexCount: toExactIntegerValue(deckOrder),
        deckOrbitCount: 1,
        stabilizerOrder: toExactIntegerValue(1n),
        representativeDeckElementKey: identityKey,
      },
      generatorTransitions,
      sphericalCellOrbits,
      sphericalFaceOrbits,
      ...(sphericalPlanSourceBound
        ? { scientificSourceBinding: sphericalPlanSourceBinding }
        : {}),
      certificate: {
        status: "passed",
        method: "exact-regular-kernel-deck-orbits",
        checks: {
          sourceBoundToDeckCertificate: true,
          deckOperationsCertifiedExact: true,
          generatorCountMatches: true,
          generatorInvolutions: generatorInvolutions.every(Boolean) as true,
          finiteCoxeterRelations: finiteRelationsPassed as true,
          sphericalPlanComplete: true,
          sphericalRestrictionsFaithful: true,
          sphericalOrbitCountsIntegral: true,
          sphericalPlanSourceBound,
        },
        deckCertificateHash: certificate.certificateHash,
        warnings: [
          ...(certificate.warnings ?? []),
          ...(sphericalPlanSourceBound
            ? []
            : [
                "No replayed SHA-256 binding joins the spherical plan to the full Coxeter input; fibering promotion is disabled.",
              ]),
        ],
      },
      completeness,
    },
    VERIFIED_SYMBOLIC_COVER,
  );
}

/** Apply one exact right-generator transition without expanding the cover. */
export function applySymbolicGeneratorTransition<Element>(
  cover: SymbolicRegularKernelCover,
  deckGroup: ExactDeckGroupOracle<Element>,
  source: Element,
  generator: number,
): Element {
  if (cover.deckGroup.id !== deckGroup.id) {
    throw new SymbolicRegularCoverError("Deck-group mismatch", [
      `Cover uses ${cover.deckGroup.id}; oracle uses ${deckGroup.id}.`,
    ]);
  }
  const transition = cover.generatorTransitions[generator];
  const factor = deckGroup.generatorImages[generator];
  if (transition === undefined || factor === undefined) {
    throw new SymbolicRegularCoverError("Unknown generator transition", [
      `Generator ${generator} is outside 0..${cover.systemRank - 1}.`,
    ]);
  }
  if (deckGroup.key(factor) !== transition.rightFactorKey) {
    throw new SymbolicRegularCoverError("Stale generator transition", [
      `Generator ${generator} no longer matches the certified deck-group image.`,
    ]);
  }
  return deckGroup.multiply(source, factor);
}

/** Read a Coxeter word as successive right transitions in H\W. */
export function traceSymbolicRegularCoverWord<Element>(
  cover: SymbolicRegularKernelCover,
  deckGroup: ExactDeckGroupOracle<Element>,
  source: Element,
  word: readonly number[],
): Element {
  return word.reduce(
    (current, generator) =>
      applySymbolicGeneratorTransition(cover, deckGroup, current, generator),
    source,
  );
}

function toSignedIntegerValue(value: bigint): SymbolicSignedIntegerValue {
  const safeInteger =
    value >= BigInt(Number.MIN_SAFE_INTEGER) &&
    value <= BigInt(Number.MAX_SAFE_INTEGER)
      ? Number(value)
      : undefined;
  return {
    decimal: value.toString(),
    ...(safeInteger === undefined ? {} : { safeInteger }),
  };
}

function signedIntegerToBigInt(
  value: SymbolicSignedIntegerValue,
  label: string,
): bigint {
  if (!/^-?(0|[1-9][0-9]*)$/.test(value.decimal)) {
    throw new SymbolicRegularCoverError("Invalid signed exact integer", [
      `${label} must be a canonical decimal integer.`,
    ]);
  }
  const exact = BigInt(value.decimal);
  if (
    value.safeInteger !== undefined &&
    (!Number.isSafeInteger(value.safeInteger) ||
      BigInt(value.safeInteger) !== exact)
  ) {
    throw new SymbolicRegularCoverError("Invalid signed exact integer", [
      `${label}.safeInteger does not equal ${value.decimal}.`,
    ]);
  }
  return exact;
}

function extendedGcd(
  left: bigint,
  right: bigint,
): {
  gcd: bigint;
  leftCoefficient: bigint;
  rightCoefficient: bigint;
} {
  let oldR = left;
  let r = right;
  let oldS = 1n;
  let s = 0n;
  let oldT = 0n;
  let t = 1n;
  while (r !== 0n) {
    const quotient = oldR / r;
    [oldR, r] = [r, oldR - quotient * r];
    [oldS, s] = [s, oldS - quotient * s];
    [oldT, t] = [t, oldT - quotient * t];
  }
  return {
    gcd: oldR,
    leftCoefficient: oldS,
    rightCoefficient: oldT,
  };
}

function bezoutCoefficients(values: readonly bigint[]): {
  gcd: bigint;
  coefficients: bigint[];
} {
  const coefficients = values.map(() => 0n);
  let gcd = 0n;
  for (let index = 0; index < values.length; index += 1) {
    const value = values[index];
    const absolute = value < 0n ? -value : value;
    if (absolute === 0n) continue;
    if (gcd === 0n) {
      gcd = absolute;
      coefficients[index] = value < 0n ? -1n : 1n;
      continue;
    }
    const step = extendedGcd(gcd, absolute);
    for (let prior = 0; prior < index; prior += 1) {
      coefficients[prior] *= step.leftCoefficient;
    }
    coefficients[index] = step.rightCoefficient * (value < 0n ? -1n : 1n);
    gcd = step.gcd;
  }
  return { gcd, coefficients };
}

