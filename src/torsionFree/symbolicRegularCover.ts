/**
 * Exact operations in a finite deck group Q.
 *
 * The oracle may use matrices, straight-line programs, or another compact
 * representation. `key` must identify equality exactly; rounded numerical
 * keys are not admissible here. Large Q need not be enumerated.
 */
export interface ExactDeckGroupOracle<Element> {
  id: string;
  name: string;
  identity: Element;
  generatorImages: readonly Element[];
  multiply(left: Element, right: Element): Element;
  inverse(element: Element): Element;
  key(element: Element): string;
  /** Optional exact order routine for the subgroup generated by these elements. */
  subgroupOrder?(generators: readonly Element[]): ExactIntegerValue;
  certificate: ExactDeckGroupCertificate;
}

