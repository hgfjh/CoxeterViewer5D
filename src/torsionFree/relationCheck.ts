/** True when `row` is a permutation of order at most two. */
export function isInvolutionRow(row: ArrayLike<number>): boolean {
  for (let point = 0; point < row.length; point += 1) {
    if (row[row[point]] !== point) return false;
  }
  return true;
}

/**
 * First point, in increasing order, where (s_left s_right)^m does not fix
 * the point, with its image; undefined when the relation holds everywhere.
 *
 * For involutions s, t one has s (st)^m s = (ts)^m = (st)^(-m), so the
 * relation holds at p exactly when it holds on the whole <s,t>-orbit of p.
 * One point per orbit is therefore checked (the orbit minimum, as points are
 * scanned in increasing order), which reports the same first failure as a
 * point-by-point scan for about 1/m of the 2m lookups per point.  Without
 * the involution hypothesis every point is checked.
 */
export function firstAlternatingRelationFailure(
  left: ArrayLike<number>,
  right: ArrayLike<number>,
  m: number,
  degree: number,
  involutions: boolean,
  /** Optional reusable scratch of at least `degree` bytes (cleared here). */
  scratch?: Uint8Array,
): { point: number; image: number } | undefined {
  let visited: Uint8Array | undefined;
  if (involutions) {
    visited =
      scratch && scratch.length >= degree
        ? scratch.subarray(0, degree)
        : new Uint8Array(degree);
    visited.fill(0);
  }
  for (let point = 0; point < degree; point += 1) {
    if (visited && visited[point] !== 0) continue;
    let image = point;
    for (let repeat = 0; repeat < m; repeat += 1) {
      image = right[left[image]];
    }
    if (image !== point) return { point, image };
    if (!visited) continue;
    // Mark the <s,t>-orbit so it is not rechecked.  For involutions the
    // orbit is the alternating walk p, sp, tsp, ... closed up within 2m
    // steps, so following the walk in one direction covers it.
    visited[point] = 1;
    let current = point;
    for (let step = 0; step < 2 * m; step += 1) {
      current = step % 2 === 0 ? left[current] : right[current];
      visited[current] = 1;
    }
  }
  return undefined;
}

/**
 * True when every orbit of the group generated by `rows` has exactly `order`
 * points, for `order` = |W_T| of the spherical subgroup W_T they generate.
 * The BFS tree of the orbit of point 0 lists all |W_T| group elements (as
 * parent/row steps), so applying that tree to any root reaches |W_T| points
 * of the root's orbit; when they are distinct the orbit has exactly |W_T|
 * points, since no orbit is larger.  This costs one row lookup per point
 * instead of one per generator per point.  False means "not shown free by
 * this test"; callers fall back to an explicit orbit walk.
 */
export function isFreeByOrbitTemplate(
  rows: readonly ArrayLike<number>[],
  degree: number,
  order: number,
  /** Optional scratch of at least `degree` bytes (cleared here). */
  scratch?: Uint8Array,
): boolean {
  if (order > degree || degree % order !== 0) return false;
  const visited =
    scratch && scratch.length >= degree
      ? scratch.subarray(0, degree)
      : new Uint8Array(degree);
  visited.fill(0);
  const templatePoints = new Uint32Array(order);
  const parent = new Int32Array(order);
  const parentRow = new Int32Array(order);
  visited[0] = 1;
  let tail = 1;
  for (let cursor = 0; cursor < tail; cursor += 1) {
    for (let k = 0; k < rows.length; k += 1) {
      const image = rows[k][templatePoints[cursor]];
      if (visited[image] !== 0) continue;
      if (tail === order) return false;
      visited[image] = 1;
      templatePoints[tail] = image;
      parent[tail] = cursor;
      parentRow[tail] = k;
      tail += 1;
    }
  }
  if (tail !== order) return false;
  const points = new Uint32Array(order);
  for (let root = 1; root < degree; root += 1) {
    if (visited[root] !== 0) continue;
    visited[root] = 1;
    points[0] = root;
    for (let local = 1; local < order; local += 1) {
      const point = rows[parentRow[local]][points[parent[local]]];
      if (visited[point] !== 0) return false;
      visited[point] = 1;
      points[local] = point;
    }
  }
  return true;
}
